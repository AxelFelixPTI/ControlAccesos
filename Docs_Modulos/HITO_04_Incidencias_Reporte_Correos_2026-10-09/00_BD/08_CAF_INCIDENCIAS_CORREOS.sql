-- -----------------------------------------------------------------------------
-- 1. CAF_Incidencia  (falta de una persona que ingresó; RN-16, RN-17)
--    Codigo: 'INC-' + ID con 5 dígitos (D-15).
--    Origen VIGILANCIA nace REGISTRADA; origen COORDINADOR nace CONFIRMADA.
--    Lugar: una zona del catálogo o un texto libre (p. ej. "Portería").
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Incidencia" (
    "ID_Incidencia"               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"                      VARCHAR(20),
    "ID_Catalogo_Sede"            BIGINT        NOT NULL,   -- ref. CAF_GOVERNANCE.Catalogo_Sede
    "ID_Catalogo_Tipo_Incidencia" BIGINT        NOT NULL,
    "Tipo_Detalle"                VARCHAR(500),             -- obligatorio si el tipo es "Otro"
    "Fecha_Hora_Hecho"            TIMESTAMP     NOT NULL,
    "ID_Catalogo_Zona_Acceso"     BIGINT,
    "Lugar_Detalle"               VARCHAR(200),
    "Descripcion"                 VARCHAR(2000) NOT NULL,
    "Origen"                      VARCHAR(20)   NOT NULL,
    "ID_Usuario_Registro"         BIGINT        NOT NULL,   -- ref. CAF_GOVERNANCE.Usuario
    "Estado"                      VARCHAR(20)   NOT NULL,
    "ID_Usuario_Decision"         BIGINT,
    "Fecha_Decision"              TIMESTAMP,
    "Sustento_Decision"           VARCHAR(2000),
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Incidencia" PRIMARY KEY ("ID_Incidencia"),
    CONSTRAINT "UQ_CAF_Incidencia_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "CK_CAF_Incidencia_Origen" CHECK ("Origen" IN ('VIGILANCIA','COORDINADOR')),
    CONSTRAINT "CK_CAF_Incidencia_Estado" CHECK ("Estado" IN ('REGISTRADA','CONFIRMADA','DESESTIMADA')),
    CONSTRAINT "CK_CAF_Incidencia_Lugar" CHECK ("ID_Catalogo_Zona_Acceso" IS NOT NULL OR "Lugar_Detalle" IS NOT NULL),
    CONSTRAINT "CK_CAF_Incidencia_Decision" CHECK ("Estado" = 'REGISTRADA' OR ("ID_Usuario_Decision" IS NOT NULL AND "Fecha_Decision" IS NOT NULL)),
    CONSTRAINT "CK_CAF_Incidencia_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Incidencia_Tipo" FOREIGN KEY ("ID_Catalogo_Tipo_Incidencia") REFERENCES "Catalogo_Tipo_Incidencia" ("ID_Catalogo_Tipo_Incidencia"),
    CONSTRAINT "FK_CAF_Incidencia_Zona" FOREIGN KEY ("ID_Catalogo_Zona_Acceso")     REFERENCES "Catalogo_Zona_Acceso" ("ID_Catalogo_Zona_Acceso")
);
CREATE INDEX "IX_CAF_Incidencia_Estado" ON "CAF_Incidencia" ("ID_Catalogo_Sede","Estado","Fecha_Hora_Hecho");

-- -----------------------------------------------------------------------------
-- 2. CAF_Incidencia_Persona  (PIVOT: una incidencia, una o varias personas)
--    Se apunta a CAF_Solicitud_Persona (la persona EN esa visita), no a la
--    persona en general: así se sabe en qué visita ocurrió.
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Incidencia_Persona" (
    "ID_Incidencia_Persona" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Incidencia"         BIGINT NOT NULL,
    "ID_Solicitud_Persona"  BIGINT NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Incidencia_Persona" PRIMARY KEY ("ID_Incidencia_Persona"),
    CONSTRAINT "UQ_CAF_Incidencia_Persona" UNIQUE ("ID_Incidencia","ID_Solicitud_Persona"),
    CONSTRAINT "CK_CAF_Incidencia_Persona_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Incidencia_Persona_Incidencia" FOREIGN KEY ("ID_Incidencia")        REFERENCES "CAF_Incidencia" ("ID_Incidencia"),
    CONSTRAINT "FK_CAF_Incidencia_Persona_Persona"    FOREIGN KEY ("ID_Solicitud_Persona") REFERENCES "CAF_Solicitud_Persona" ("ID_Solicitud_Persona")
);
CREATE INDEX "IX_CAF_Incidencia_Persona_Persona" ON "CAF_Incidencia_Persona" ("ID_Solicitud_Persona");

-- Enlace opcional desviación -> incidencia (definido aquí porque CAF_Incidencia
-- se crea después que CAF_Desviacion).
ALTER TABLE "CAF_Desviacion"
  ADD CONSTRAINT "FK_CAF_Desviacion_Incidencia" FOREIGN KEY ("ID_Incidencia") REFERENCES "CAF_Incidencia" ("ID_Incidencia");

-- -----------------------------------------------------------------------------
-- 3. CAF_Correo_Pendiente  (bandeja de salida de correos; RF-41, D-19)
--    El SP de negocio solo INSERTA aquí; un proceso en segundo plano envía y
--    marca ENVIADO o ERROR. Si el correo falla, la aprobación no se pierde.
--    Cuerpo: HTML del correo. Excepción justificada a "sin textos largos"
--    (tabla de cola, no se agrupa ni se filtra por este campo). HANA: NCLOB.
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Correo_Pendiente" (
    "ID_Correo_Pendiente" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Tipo"                VARCHAR(50)   NOT NULL,
    "ID_Solicitud"        BIGINT,
    "Destinatarios"       VARCHAR(2000) NOT NULL,
    "Copia"               VARCHAR(2000),
    "Asunto"              VARCHAR(500)  NOT NULL,
    "Cuerpo"              TEXT          NOT NULL,
    "Estado"              VARCHAR(20)   DEFAULT 'PENDIENTE' NOT NULL,
    "Intentos"            BIGINT        DEFAULT 0 NOT NULL,
    "Ultimo_Error"        VARCHAR(1000),
    "Fecha_Envio"         TIMESTAMP,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Correo_Pendiente" PRIMARY KEY ("ID_Correo_Pendiente"),
    CONSTRAINT "CK_CAF_Correo_Pendiente_Tipo" CHECK ("Tipo" IN ('SOLICITUD_NUEVA','SOLICITUD_EDITADA','SOLICITUD_OBSERVADA','SOLICITUD_APROBADA','SOLICITUD_CANCELADA','USUARIO_DEFINIR_PASSWORD')),
    CONSTRAINT "CK_CAF_Correo_Pendiente_Estado" CHECK ("Estado" IN ('PENDIENTE','ENVIADO','ERROR')),
    CONSTRAINT "CK_CAF_Correo_Pendiente_Intentos" CHECK ("Intentos" >= 0),
    CONSTRAINT "CK_CAF_Correo_Pendiente_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Correo_Pendiente_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);
CREATE INDEX "IX_CAF_Correo_Pendiente_Estado" ON "CAF_Correo_Pendiente" ("Estado","CreateDate");
