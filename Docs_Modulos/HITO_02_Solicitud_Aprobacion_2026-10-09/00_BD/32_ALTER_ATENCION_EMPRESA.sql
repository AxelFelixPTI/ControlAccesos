-- Atención de Almacén POR EMPRESA receptora (Entrega 2C-1).
--   1. CAF_Solicitud_Atencion: una fila por solicitud y empresa receptora, con su estado de atención
--      (PENDIENTE, EN_ATENCION, ATENDIDA, CERRADA_SIN_ATENCION). Las filas se crean al primer movimiento; mientras no existan,
--      los lectores derivan el estado del estado operativo de la solicitud (así no hay migración de datos).
--   2. CAF_Motivo_Sin_Atencion: motivos para «Cerrar sin atención» (lista corta + «Otro» que exige detalle).
--   3. Parámetro ATENCIONES_SIMULTANEAS_EMPRESA (por defecto 1): cuántas entregas puede estar atendiendo a la vez una misma empresa.
-- Se puede ejecutar más de una vez. Requiere el script 30. Schema: TRIANONSATELITAL_CAF_PRODD.
-- HANA (T-44): sin índices únicos parciales (validar en el SP con candado) ni IF NOT EXISTS en CREATE TABLE (consultar SYS.TABLES).
-- =============================================================================
SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

CREATE TABLE IF NOT EXISTS "CAF_Motivo_Sin_Atencion" (
    "ID_Motivo_Sin_Atencion" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"      VARCHAR(30)  NOT NULL,
    "Descripcion" VARCHAR(120) NOT NULL,
    "Es_Otro"     CHAR(1)   DEFAULT 'N' NOT NULL,        -- 'Y' = exige describir el motivo
    "Orden"       INT       DEFAULT 0 NOT NULL,
    "Activo"      CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Motivo_Sin_Atencion" PRIMARY KEY ("ID_Motivo_Sin_Atencion"),
    CONSTRAINT "UQ_CAF_Motivo_Sin_Atencion_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "CK_CAF_Motivo_Sin_Atencion_Flags" CHECK ("Es_Otro" IN ('Y','N') AND "Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N'))
);
INSERT INTO "CAF_Motivo_Sin_Atencion" ("Codigo","Descripcion","Es_Otro","Orden","UsuarioID_Create")
SELECT V.c, V.d, V.o, V.n, 0 FROM (VALUES
    ('SIN_MERCADERIA', 'No llegó mercadería para esta empresa', 'N', 1),
    ('RECHAZADA',      'Rechazada por Almacén',                 'N', 2),
    ('OTRA_ENTREGA',   'Se atenderá en otra entrega',           'N', 3),
    ('OTRO',           'Otro (describa el motivo)',             'Y', 9)) AS V(c, d, o, n)
 WHERE NOT EXISTS (SELECT 1 FROM "CAF_Motivo_Sin_Atencion" M WHERE M."Codigo" = V.c);

CREATE TABLE IF NOT EXISTS "CAF_Solicitud_Atencion" (
    "ID_Solicitud_Atencion"     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"              BIGINT       NOT NULL,
    "ID_Catalogo_Empresa_Grupo" BIGINT       NOT NULL,            -- ref. CAF_GOVERNANCE.Catalogo_Empresa_Grupo
    "Estado"                    VARCHAR(25)  DEFAULT 'PENDIENTE' NOT NULL,
    "Fecha_Inicio"              TIMESTAMP,
    "ID_Usuario_Inicio"         BIGINT,
    "Fecha_Fin"                 TIMESTAMP,
    "ID_Usuario_Fin"            BIGINT,
    "Resultado"                 VARCHAR(20),                      -- CONFORME | CON_OBSERVACION (solo ATENDIDA)
    "Observacion"               VARCHAR(1000),
    "ID_Motivo_Sin_Atencion"    BIGINT,                           -- solo CERRADA_SIN_ATENCION
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Atencion" PRIMARY KEY ("ID_Solicitud_Atencion"),
    CONSTRAINT "CK_CAF_Solicitud_Atencion_Estado" CHECK ("Estado" IN ('PENDIENTE','EN_ATENCION','ATENDIDA','CERRADA_SIN_ATENCION')),
    CONSTRAINT "CK_CAF_Solicitud_Atencion_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Atencion_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud"),
    CONSTRAINT "FK_CAF_Solicitud_Atencion_Motivo" FOREIGN KEY ("ID_Motivo_Sin_Atencion") REFERENCES "CAF_Motivo_Sin_Atencion" ("ID_Motivo_Sin_Atencion")
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_CAF_Solicitud_Atencion" ON "CAF_Solicitud_Atencion" ("ID_Solicitud","ID_Catalogo_Empresa_Grupo") WHERE "Eliminado" = 'N';
CREATE INDEX IF NOT EXISTS "IX_CAF_Solicitud_Atencion_Empresa" ON "CAF_Solicitud_Atencion" ("ID_Catalogo_Empresa_Grupo","Estado") WHERE "Eliminado" = 'N';

INSERT INTO "CAF_Parametro" ("Clave","Valor","Descripcion","UsuarioID_Create")
SELECT 'ATENCIONES_SIMULTANEAS_EMPRESA', '1', 'Entregas que una misma empresa del grupo puede estar atendiendo a la vez (por empresa receptora). Si se alcanza, Almacén debe terminar una antes de iniciar otra.', 0
 WHERE NOT EXISTS (SELECT 1 FROM "CAF_Parametro" WHERE "Clave" = 'ATENCIONES_SIMULTANEAS_EMPRESA');
