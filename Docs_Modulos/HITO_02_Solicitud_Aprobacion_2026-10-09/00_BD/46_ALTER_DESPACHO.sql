-- 7. Checklist -------------------------------------------------------------------------------------------
-- Ingreso: se reutilizan identidad y placa. Salida: ítem nuevo con la revisión de la guía de remisión (crítico).
INSERT INTO "Catalogo_Item_Checklist" ("Codigo","Descripcion","Ayuda","Etapa","Condicion","Es_Critico","Orden","UsuarioID_Create")
SELECT 'SAL_DESPACHO_GUIA',
       'Guía de remisión revisada: los productos que salen coinciden con la guía (OF/OV) y todo está correcto.',
       'Revise la guía de remisión contra la carga antes de dejar salir el vehículo.', 'SALIDA', 'SIEMPRE', 'Y', 11, 0
 WHERE NOT EXISTS (SELECT 1 FROM "Catalogo_Item_Checklist" WHERE "Codigo" = 'SAL_DESPACHO_GUIA');

INSERT INTO "Tipo_Acceso_Item_Checklist" ("ID_Catalogo_Tipo_Acceso","ID_Catalogo_Item_Checklist","ID_Tipo_Acceso_Subtipo","UsuarioID_Create")
SELECT t."ID_Catalogo_Tipo_Acceso", i."ID_Catalogo_Item_Checklist", s."ID_Tipo_Acceso_Subtipo", 0
  FROM "Catalogo_Tipo_Acceso" t
  JOIN "Catalogo_Item_Checklist" i ON i."Codigo" IN ('ING_IDENTIDAD','ING_PLACA','SAL_DESPACHO_GUIA')
  JOIN "Tipo_Acceso_Subtipo" s ON s."ID_Catalogo_Tipo_Acceso" = t."ID_Catalogo_Tipo_Acceso" AND s."Codigo" = 'TRANSPORTISTA'
 WHERE t."Codigo" = 'DESPACHO'
   AND NOT EXISTS (SELECT 1 FROM "Tipo_Acceso_Item_Checklist" x
                    WHERE x."ID_Catalogo_Tipo_Acceso" = t."ID_Catalogo_Tipo_Acceso" AND x."ID_Catalogo_Item_Checklist" = i."ID_Catalogo_Item_Checklist");

