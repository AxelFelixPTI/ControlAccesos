-- Qué hace:
--   1. Tipo de ingreso nuevo «DESPACHO» (Despacho: salida de productos), disponible, con aprobación del Coordinador
--      por solicitud (licencia propia LIC_CAF_COORD_DESPACHO, que se concede una sola vez a quienes ya tienen
--      LIC_CAF_COORD_PROVEEDOR).
--   2. Quien solicita: permiso PER_CAF_DESPACHO_SOLICITAR + licencia LIC_CAF_SOLICITANTE_DESPACHO (Ventas, y Almacén si
--      el administrador se la asigna). Vigilancia y Almacén reutilizan los permisos de proveedores (misma forma de atención).
--   3. CAF_Solicitud: N.° de OF (en vez de OC), N.° de OV, N.° de orden y tipo de transporte del despacho.
--   4. CAF_Despacho_Config_Empresa: por empresa del grupo, qué tipos de transporte se permiten y cuál es el
--      predeterminado. Con un solo tipo permitido el transporte queda FIJO; con varios, el solicitante elige.
--      Lo edita solo el Administrador (más adelante, la reestructuración de permisos la repartirá por subgrupos).
--   5. Subtipo único «Conductor» (código TRANSPORTISTA, como en proveedor; el despacho NO tiene ayudante de descarga).
--   6. Checklist: ingreso (identidad, placa) y salida (revisión de la guía de remisión).
--   7. Parámetros: modo del dashboard (PROVEEDORES / DESPACHOS / AMBOS) y activar o no «sin ingreso vehicular» por tipo.
--   8. Catalogo_Sede.Aplica_Despacho (VES = 'Y') y motivo fijo «Despacho de productos».
-- HANA: ADD COLUMN IF NOT EXISTS no existe (se consulta SYS.TABLE_COLUMNS antes); CHECK con ADD CONSTRAINT.
-- =============================================================================

-- 1. Sede ------------------------------------------------------------------------------------------
SET search_path TO "CAF_GOVERNANCE";
ALTER TABLE "Catalogo_Sede" ADD COLUMN IF NOT EXISTS "Aplica_Despacho" CHAR(1) DEFAULT 'N' NOT NULL;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_Catalogo_Sede_Despacho') THEN
        ALTER TABLE "CAF_GOVERNANCE"."Catalogo_Sede" ADD CONSTRAINT "CK_Catalogo_Sede_Despacho" CHECK ("Aplica_Despacho" IN ('Y','N'));
    END IF;
END $$;
UPDATE "Catalogo_Sede" SET "Aplica_Despacho" = 'Y' WHERE "Codigo" = 'VES' AND "Aplica_Despacho" = 'N'
   AND NOT EXISTS (SELECT 1 FROM "CAF_GOVERNANCE"."Catalogo_Sede" X WHERE X."Codigo" = 'VES' AND X."Aplica_Despacho" = 'Y');

-- 2. Solicitud: datos propios del despacho --------------------------------------------------------
SET search_path TO "TRIANONSATELITAL_CAF_PRODD";
ALTER TABLE "CAF_Solicitud" ADD COLUMN IF NOT EXISTS "Numeros_OF"         VARCHAR(200);   -- órdenes de fabricación (1 a 5, ';')
ALTER TABLE "CAF_Solicitud" ADD COLUMN IF NOT EXISTS "Numeros_OV"         VARCHAR(200);   -- órdenes de venta (opcional, ';')
ALTER TABLE "CAF_Solicitud" ADD COLUMN IF NOT EXISTS "Numeros_Orden"      VARCHAR(200);   -- N.° de orden (opcional, ';')
ALTER TABLE "CAF_Solicitud" ADD COLUMN IF NOT EXISTS "Despacho_Transporte" VARCHAR(20);   -- SERVICIO_APP | PROPIO_CLIENTE | CONTRATADO
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_CAF_Solicitud_Despacho_Transporte') THEN
        ALTER TABLE "TRIANONSATELITAL_CAF_PRODD"."CAF_Solicitud" ADD CONSTRAINT "CK_CAF_Solicitud_Despacho_Transporte"
            CHECK ("Despacho_Transporte" IS NULL OR "Despacho_Transporte" IN ('SERVICIO_APP','PROPIO_CLIENTE','CONTRATADO'));
    END IF;
END $$;

-- 3. Configuración de transporte por empresa -------------------------------------------------------
CREATE TABLE IF NOT EXISTS "CAF_Despacho_Config_Empresa" (
    "ID_Despacho_Config_Empresa"  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "ID_Catalogo_Empresa_Grupo"   BIGINT       NOT NULL,
    "Transportes_Permitidos"      VARCHAR(60)  NOT NULL,                 -- códigos separados por ';'
    "Transporte_Predeterminado"   VARCHAR(20)  NOT NULL,
    "Eliminado"                   CHAR(1)      NOT NULL DEFAULT 'N',
    "UsuarioID_Create"            BIGINT       NOT NULL,
    "UsuarioID_Update"            BIGINT,
    "CreateDate"                  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdateDate"                  TIMESTAMP,
    CONSTRAINT "PK_CAF_Despacho_Config_Empresa" PRIMARY KEY ("ID_Despacho_Config_Empresa"),
    CONSTRAINT "UQ_CAF_Despacho_Config_Empresa" UNIQUE ("ID_Catalogo_Empresa_Grupo"),
    CONSTRAINT "CK_CAF_Despacho_Config_Elim" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "CK_CAF_Despacho_Config_Pred" CHECK ("Transporte_Predeterminado" IN ('SERVICIO_APP','PROPIO_CLIENTE','CONTRATADO'))
);

-- Valores iniciales (el administrador los cambia): PT y TA despachan con servicio tipo Cabify; TE y TS con transporte
-- del cliente o contratado por la empresa.
INSERT INTO "CAF_Despacho_Config_Empresa" ("ID_Catalogo_Empresa_Grupo","Transportes_Permitidos","Transporte_Predeterminado","UsuarioID_Create")
SELECT E."ID_Catalogo_Empresa_Grupo",
       CASE WHEN E."Codigo" IN ('POWER_TECHNOLOGY','TRIANON_ASCENSORES') THEN 'SERVICIO_APP' ELSE 'PROPIO_CLIENTE;CONTRATADO' END,
       CASE WHEN E."Codigo" IN ('POWER_TECHNOLOGY','TRIANON_ASCENSORES') THEN 'SERVICIO_APP' ELSE 'PROPIO_CLIENTE' END,
       0
  FROM "CAF_GOVERNANCE"."Catalogo_Empresa_Grupo" E
 WHERE NOT EXISTS (SELECT 1 FROM "CAF_Despacho_Config_Empresa" C WHERE C."ID_Catalogo_Empresa_Grupo" = E."ID_Catalogo_Empresa_Grupo");

-- 4. Permisos y licencias --------------------------------------------------------------------------
SET search_path TO "CAF_GOVERNANCE";
INSERT INTO "Catalogo_Permiso" ("Codigo","Descripcion","Modulo","Orden","UsuarioID_Create")
SELECT 'PER_CAF_DESPACHO_SOLICITAR','Solicitar el despacho (salida de productos) de una entrega al cliente','ACCESOS',20,0
 WHERE NOT EXISTS (SELECT 1 FROM "Catalogo_Permiso" WHERE "Codigo" = 'PER_CAF_DESPACHO_SOLICITAR');

INSERT INTO "Catalogo_Licencia" ("Codigo","Descripcion","Modulo","Orden","UsuarioID_Create")
SELECT v.cod, v.descr, 'ACCESOS', v.ord, 0
  FROM (VALUES ('LIC_CAF_SOLICITANTE_DESPACHO','Solicitante de despachos (Ventas; también Almacén si se le asigna)', 27),
               ('LIC_CAF_COORD_DESPACHO',      'Coordinador de despachos (aprueba cada solicitud de despacho)',        28)) AS v(cod, descr, ord)
 WHERE NOT EXISTS (SELECT 1 FROM "Catalogo_Licencia" L WHERE L."Codigo" = v.cod);

INSERT INTO "Licencia_Permiso" ("ID_Catalogo_Licencia","ID_Catalogo_Permiso","UsuarioID_Create")
SELECT l."ID_Catalogo_Licencia", p."ID_Catalogo_Permiso", 0
  FROM (VALUES
    ('LIC_CAF_SOLICITANTE_DESPACHO','PER_CAF_DESPACHO_SOLICITAR'),
    ('LIC_CAF_COORD_DESPACHO',      'PER_CAF_SOLICITUD_APROBAR'),
    ('LIC_CAF_COORD_DESPACHO',      'PER_CAF_PROVEEDOR_VER'),
    ('LIC_CAF_COORD_DESPACHO',      'PER_CAF_PORTERIA_VER'),
    ('LIC_CAF_COORD_DESPACHO',      'PER_CAF_DESVIACION_CONFORMIDAD')
  ) AS v(lic, per)
  JOIN "Catalogo_Licencia" l ON l."Codigo" = v.lic
  JOIN "Catalogo_Permiso"  p ON p."Codigo" = v.per
 WHERE NOT EXISTS (SELECT 1 FROM "Licencia_Permiso" X WHERE X."ID_Catalogo_Licencia" = l."ID_Catalogo_Licencia" AND X."ID_Catalogo_Permiso" = p."ID_Catalogo_Permiso");

-- Valor inicial (una sola vez): quienes ya coordinan proveedores reciben también la licencia de coordinador de despachos.
-- Se detecta «una sola vez» porque la licencia nueva todavía no tiene ningún usuario asignado.
SET search_path TO "CAF_GOVERNANCE";
DO $$
DECLARE
    lv_lic BIGINT;
    lv_n   INT;
BEGIN
    SELECT "ID_Catalogo_Licencia" INTO lv_lic FROM "CAF_GOVERNANCE"."Catalogo_Licencia" WHERE "Codigo" = 'LIC_CAF_COORD_DESPACHO';
    SELECT COUNT(*) INTO lv_n FROM "CAF_GOVERNANCE"."Usuario_Licencia" WHERE "ID_Catalogo_Licencia" = lv_lic;
    IF lv_n = 0 THEN
        INSERT INTO "CAF_GOVERNANCE"."Usuario_Licencia" ("ID_Usuario","ID_Catalogo_Licencia","ID_Catalogo_Sede","UsuarioID_Create")
        SELECT UL."ID_Usuario", lv_lic, UL."ID_Catalogo_Sede", 0
          FROM "CAF_GOVERNANCE"."Usuario_Licencia" UL
          JOIN "CAF_GOVERNANCE"."Catalogo_Licencia" CL ON CL."ID_Catalogo_Licencia" = UL."ID_Catalogo_Licencia" AND CL."Codigo" = 'LIC_CAF_COORD_PROVEEDOR'
         WHERE UL."Eliminado" = 'N';
    END IF;
END $$;

-- 5. Tipo de ingreso DESPACHO + paso de aprobación + subtipo ----------------------------------------
SET search_path TO "TRIANONSATELITAL_CAF_PRODD";
INSERT INTO "Catalogo_Tipo_Acceso" ("Codigo","Descripcion","Requiere_Aprobacion","Disponible","Orden","UsuarioID_Create")
SELECT 'DESPACHO','Despacho (salida de productos)','Y','Y',
       COALESCE((SELECT MAX("Orden") FROM "Catalogo_Tipo_Acceso"), 0) + 1, 0
 WHERE NOT EXISTS (SELECT 1 FROM "Catalogo_Tipo_Acceso" WHERE "Codigo" = 'DESPACHO');

INSERT INTO "Tipo_Acceso_Paso_Aprobacion"
  ("ID_Catalogo_Tipo_Acceso","Orden","Codigo","Descripcion","Alcance","Tipo_Aprobador","ID_Catalogo_Licencia","Condicion","Obligatorio","UsuarioID_Create")
SELECT t."ID_Catalogo_Tipo_Acceso", 1, 'AUTORIZACION', 'Autorización del Coordinador de despachos', 'PERSONA', 'ROL', l."ID_Catalogo_Licencia", 'SIEMPRE', 'Y', 0
  FROM "Catalogo_Tipo_Acceso" t, "CAF_GOVERNANCE"."Catalogo_Licencia" l
 WHERE t."Codigo" = 'DESPACHO' AND l."Codigo" = 'LIC_CAF_COORD_DESPACHO'
   AND NOT EXISTS (SELECT 1 FROM "Tipo_Acceso_Paso_Aprobacion" P WHERE P."ID_Catalogo_Tipo_Acceso" = t."ID_Catalogo_Tipo_Acceso" AND P."Codigo" = 'AUTORIZACION');

INSERT INTO "Tipo_Acceso_Subtipo" ("ID_Catalogo_Tipo_Acceso","Codigo","Descripcion","Orden","Es_Predeterminado","UsuarioID_Create")
SELECT t."ID_Catalogo_Tipo_Acceso", 'TRANSPORTISTA', 'Conductor', 1, 'Y', 0
  FROM "Catalogo_Tipo_Acceso" t
 WHERE t."Codigo" = 'DESPACHO'
   AND NOT EXISTS (SELECT 1 FROM "Tipo_Acceso_Subtipo" s WHERE s."ID_Catalogo_Tipo_Acceso" = t."ID_Catalogo_Tipo_Acceso" AND s."Codigo" = 'TRANSPORTISTA');

-- 6. Motivo fijo ---------------------------------------------------------------------------------------
INSERT INTO "Catalogo_Motivo_Visita" ("Codigo","Descripcion","Es_Otro","Orden","UsuarioID_Create")
