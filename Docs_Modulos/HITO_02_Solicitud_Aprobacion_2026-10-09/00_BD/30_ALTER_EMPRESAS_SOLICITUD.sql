-- Una solicitud de proveedor puede estar ligada a 1 a 4 empresas del grupo (PT, TA, TE, TS).
--   1. CAF_Solicitud_Empresa: las empresas de la solicitud (eliminado lógico; una fila activa por solicitud y empresa).
--      CAF_Solicitud.ID_Catalogo_Empresa_Grupo_Destino se conserva como «empresa principal» (la primera) para los lectores antiguos.
--   2. Migración: cada solicitud con empresa recibe su fila. Un trigger deja la fila si alguna ruta antigua solo escribe la columna.
--   3. CAF_Usuario_Empresa_Almacen: a qué empresas puede dar atención cada usuario de Almacén (no depende de quién lo contrató).
--      Se siembra con las 4 empresas para quien hoy tiene la licencia LIC_CAF_ALMACEN; el administrador lo ajusta después.
-- Se puede ejecutar más de una vez. Schema: TRIANONSATELITAL_CAF_PRODD.
-- HANA (T-42): sin índices únicos parciales (se valida en el SP); el trigger se reescribe en SQLScript.
-- =============================================================================
SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

CREATE TABLE IF NOT EXISTS "CAF_Solicitud_Empresa" (
    "ID_Solicitud_Empresa"      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"              BIGINT    NOT NULL,
    "ID_Catalogo_Empresa_Grupo" BIGINT    NOT NULL,            -- ref. CAF_GOVERNANCE.Catalogo_Empresa_Grupo
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Empresa" PRIMARY KEY ("ID_Solicitud_Empresa"),
    CONSTRAINT "CK_CAF_Solicitud_Empresa_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Empresa_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_CAF_Solicitud_Empresa" ON "CAF_Solicitud_Empresa" ("ID_Solicitud","ID_Catalogo_Empresa_Grupo") WHERE "Eliminado" = 'N';

-- Migración de lo existente
INSERT INTO "CAF_Solicitud_Empresa" ("ID_Solicitud","ID_Catalogo_Empresa_Grupo","UsuarioID_Create")
SELECT S."ID_Solicitud", S."ID_Catalogo_Empresa_Grupo_Destino", 0
  FROM "CAF_Solicitud" S
 WHERE S."ID_Catalogo_Empresa_Grupo_Destino" IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM "CAF_Solicitud_Empresa" E WHERE E."ID_Solicitud" = S."ID_Solicitud" AND E."Eliminado" = 'N');

CREATE OR REPLACE FUNCTION "TRG_CAF_Solicitud_Empresa_Principal"() RETURNS trigger
LANGUAGE plpgsql SET search_path TO "TRIANONSATELITAL_CAF_PRODD" AS $$
BEGIN
    IF NEW."ID_Catalogo_Empresa_Grupo_Destino" IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM "CAF_Solicitud_Empresa" E WHERE E."ID_Solicitud" = NEW."ID_Solicitud" AND E."Eliminado" = 'N') THEN
        INSERT INTO "CAF_Solicitud_Empresa" ("ID_Solicitud","ID_Catalogo_Empresa_Grupo","UsuarioID_Create")
        VALUES (NEW."ID_Solicitud", NEW."ID_Catalogo_Empresa_Grupo_Destino", 0);
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "TR_CAF_Solicitud_Empresa_Principal" ON "CAF_Solicitud";
CREATE TRIGGER "TR_CAF_Solicitud_Empresa_Principal" AFTER INSERT OR UPDATE OF "ID_Catalogo_Empresa_Grupo_Destino" ON "CAF_Solicitud"
    FOR EACH ROW EXECUTE FUNCTION "TRG_CAF_Solicitud_Empresa_Principal"();

-- Empresas a las que cada usuario de Almacén puede dar atención
CREATE TABLE IF NOT EXISTS "CAF_Usuario_Empresa_Almacen" (
    "ID_Usuario_Empresa_Almacen" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Usuario"                 BIGINT    NOT NULL,           -- ref. CAF_GOVERNANCE.Usuario
    "ID_Catalogo_Empresa_Grupo"  BIGINT    NOT NULL,           -- ref. CAF_GOVERNANCE.Catalogo_Empresa_Grupo
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Usuario_Empresa_Almacen" PRIMARY KEY ("ID_Usuario_Empresa_Almacen"),
    CONSTRAINT "CK_CAF_Usuario_Empresa_Almacen_Flags" CHECK ("Eliminado" IN ('Y','N'))
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_CAF_Usuario_Empresa_Almacen" ON "CAF_Usuario_Empresa_Almacen" ("ID_Usuario","ID_Catalogo_Empresa_Grupo") WHERE "Eliminado" = 'N';

INSERT INTO "CAF_Usuario_Empresa_Almacen" ("ID_Usuario","ID_Catalogo_Empresa_Grupo","UsuarioID_Create")
SELECT DISTINCT UL."ID_Usuario", EG."ID_Catalogo_Empresa_Grupo", 0
  FROM "CAF_GOVERNANCE"."Usuario_Licencia" UL
  JOIN "CAF_GOVERNANCE"."Catalogo_Licencia" L ON L."ID_Catalogo_Licencia" = UL."ID_Catalogo_Licencia" AND L."Codigo" = 'LIC_CAF_ALMACEN' AND L."Eliminado" = 'N'
 CROSS JOIN "CAF_GOVERNANCE"."Catalogo_Empresa_Grupo" EG
 WHERE UL."Eliminado" = 'N' AND EG."Eliminado" = 'N' AND EG."Activo" = 'Y'
   AND NOT EXISTS (SELECT 1 FROM "CAF_Usuario_Empresa_Almacen" X WHERE X."ID_Usuario" = UL."ID_Usuario" AND X."ID_Catalogo_Empresa_Grupo" = EG."ID_Catalogo_Empresa_Grupo" AND X."Eliminado" = 'N');
