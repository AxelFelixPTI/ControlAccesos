-- Días autorizados de una solicitud de CONTRATISTA (franja de tiempo). Una fila por día: pueden ser
-- consecutivos y/o sueltos (jueves, viernes y lunes siguiente; interdiario por dos semanas...).
-- Hora_Desde / Hora_Hasta son hora APROXIMADA de ingreso y de salida, OPCIONALES e independientes (solo informativas: no restringen); el mismo horario se copia a
-- cada día al crearlo. Dentro de la franja la persona puede ingresar y salir varias veces; fuera de ella
-- Vigilancia solo puede autorizar el ingreso con desviación.
-- La solicitud sigue guardando en Fecha_Hora_Prevista su PRIMER día (calendario, listas y solicitudes de un solo
-- día anteriores a este script siguen igual: una solicitud sin filas aquí se comporta como siempre).
-- Los días no se borran: la extensión del Coordinador solo agrega (Origen = 'EXTENSION').
-- HANA: sin índices parciales; la unicidad (solicitud, fecha) es total porque nunca se borran días.
-- Aditivo: solo crea una tabla. Va en una transacción y se ejecuta UNA vez.
-- =============================================================================

BEGIN;

DO $$
BEGIN
    IF to_regclass('"TRIANONSATELITAL_CAF_PRODD"."CAF_Solicitud_Transportista"') IS NULL THEN
        RAISE EXCEPTION 'Faltan los scripts 01 a 24.';
    END IF;
    IF to_regclass('"TRIANONSATELITAL_CAF_PRODD"."CAF_Solicitud_Dia"') IS NOT NULL THEN
        RAISE EXCEPTION 'El script 25 ya se ejecutó. No se repite.';
    END IF;
END $$;

SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

CREATE TABLE "CAF_Solicitud_Dia" (
    "ID_Solicitud_Dia"  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"      BIGINT      NOT NULL,
    "Fecha"             DATE        NOT NULL,
    "Hora_Desde"        TIME,
    "Hora_Hasta"        TIME,
    "Origen"            VARCHAR(10) DEFAULT 'SOLICITUD' NOT NULL,
    "Eliminado"         CHAR(1)     DEFAULT 'N' NOT NULL,
    "UsuarioID_Create"  BIGINT      NOT NULL,
    "UsuarioID_Update"  BIGINT,
    "CreateDate"        TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"        TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Dia" PRIMARY KEY ("ID_Solicitud_Dia"),
    CONSTRAINT "UQ_CAF_Solicitud_Dia_Fecha" UNIQUE ("ID_Solicitud", "Fecha"),
    CONSTRAINT "CK_CAF_Solicitud_Dia_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "CK_CAF_Solicitud_Dia_Origen" CHECK ("Origen" IN ('SOLICITUD','EXTENSION')),
    CONSTRAINT "CK_CAF_Solicitud_Dia_Horas" CHECK ("Hora_Desde" IS NULL OR "Hora_Hasta" IS NULL OR "Hora_Desde" < "Hora_Hasta"),
    CONSTRAINT "FK_CAF_Solicitud_Dia_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);
CREATE INDEX "IX_CAF_Solicitud_Dia_Fecha" ON "CAF_Solicitud_Dia" ("Fecha", "ID_Solicitud");

COMMIT;
