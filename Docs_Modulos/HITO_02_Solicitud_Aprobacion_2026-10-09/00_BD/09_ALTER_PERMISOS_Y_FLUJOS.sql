    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Licencia_Permiso" PRIMARY KEY ("ID_Licencia_Permiso"),
    CONSTRAINT "UQ_Licencia_Permiso" UNIQUE ("ID_Catalogo_Licencia","ID_Catalogo_Permiso"),
    CONSTRAINT "CK_Licencia_Permiso_Flags" CHECK ("Eliminado" IN ('Y','N')),
