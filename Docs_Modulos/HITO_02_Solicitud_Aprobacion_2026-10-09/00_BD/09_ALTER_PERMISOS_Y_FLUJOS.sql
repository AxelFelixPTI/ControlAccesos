CREATE TABLE "Catalogo_Permiso" (
    "ID_Catalogo_Permiso" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"           VARCHAR(50)  NOT NULL,
    "Descripcion"      VARCHAR(500) NOT NULL,
    "Modulo"           VARCHAR(50)  NOT NULL,
    "Orden"            BIGINT    DEFAULT 0   NOT NULL,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Catalogo_Permiso" PRIMARY KEY ("ID_Catalogo_Permiso"),
    CONSTRAINT "UQ_Catalogo_Permiso_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "CK_Catalogo_Permiso_Flags" CHECK ("Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N'))
);
CREATE INDEX "IX_Catalogo_Permiso_Activa" ON "Catalogo_Permiso" ("Eliminado","Activo","Orden");

-- -----------------------------------------------------------------------------
-- 1.2 Licencia_Permiso  (PIVOT rol-permiso: qué puertas abre cada rol)
