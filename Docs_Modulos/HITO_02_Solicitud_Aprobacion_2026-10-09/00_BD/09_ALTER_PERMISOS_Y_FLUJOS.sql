ALTER TABLE "CAF_Solicitud_Persona" ADD CONSTRAINT "CK_CAF_Solicitud_Persona_Aprobacion"
  CHECK ("Aprobacion" IN ('PENDIENTE','APROBADA','OBSERVADA','RECHAZADA','RETIRADA'));
ALTER TABLE "CAF_Solicitud_Persona" ADD CONSTRAINT "CK_CAF_Solicitud_Persona_Origen"
  CHECK ("Origen" IN ('SOLICITUD','AGREGADA','AGREGADA_COORDINADOR','REENVIADA','REABIERTA'));
