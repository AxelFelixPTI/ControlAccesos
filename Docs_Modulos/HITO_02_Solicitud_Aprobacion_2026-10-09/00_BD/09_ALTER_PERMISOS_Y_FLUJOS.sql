ALTER TABLE "CAF_Solicitud_Persona" ADD CONSTRAINT "CK_CAF_Solicitud_Persona_Motivo"
  CHECK ("Aprobacion" NOT IN ('OBSERVADA','RECHAZADA') OR ("Aprobacion_Mensaje" IS NOT NULL AND LENGTH(TRIM("Aprobacion_Mensaje")) > 0));
-- Solo una persona APROBADA puede tener movimientos en portería.
ALTER TABLE "CAF_Solicitud_Persona" ADD CONSTRAINT "CK_CAF_Solicitud_Persona_Ingreso"
  CHECK ("Estado" = 'ESPERADA' OR "Aprobacion" = 'APROBADA');
-- Listado de Vigilancia: personas aprobadas de una solicitud.
CREATE INDEX "IX_CAF_Solicitud_Persona_Aprobacion" ON "CAF_Solicitud_Persona" ("ID_Solicitud","Aprobacion","Eliminado");

-- -----------------------------------------------------------------------------
-- 2.3 CAF_Solicitud_Decision  (una fila por persona y paso: el "sello")
--     Para un paso de alcance SOLICITUD se guarda igual una fila por persona,
--     con el mismo usuario y fecha: así el cálculo del estado es uno solo y las
--     personas que llegan después heredan ese paso sin reabrirlo.
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Solicitud_Decision" (
    "ID_Solicitud_Decision" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud_Persona"  BIGINT       NOT NULL,
    "ID_Tipo_Acceso_Paso_Aprobacion" BIGINT NOT NULL,
    "Decision"              VARCHAR(20)  NOT NULL,
    "Mensaje"               VARCHAR(2000),
    "ID_Usuario"            BIGINT       NOT NULL,   -- ref. CAF_GOVERNANCE.Usuario
    "Fecha_Decision"        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "Vigente"               CHAR(1)      DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Decision" PRIMARY KEY ("ID_Solicitud_Decision"),
    CONSTRAINT "CK_CAF_Solicitud_Decision_Valor" CHECK ("Decision" IN ('APROBADA','OBSERVADA','RECHAZADA')),
    CONSTRAINT "CK_CAF_Solicitud_Decision_Motivo" CHECK ("Decision" = 'APROBADA' OR ("Mensaje" IS NOT NULL AND LENGTH(TRIM("Mensaje")) > 0)),
    CONSTRAINT "CK_CAF_Solicitud_Decision_Flags" CHECK ("Vigente" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Decision_Persona" FOREIGN KEY ("ID_Solicitud_Persona") REFERENCES "CAF_Solicitud_Persona" ("ID_Solicitud_Persona"),
    CONSTRAINT "FK_CAF_Solicitud_Decision_Paso"    FOREIGN KEY ("ID_Tipo_Acceso_Paso_Aprobacion") REFERENCES "Tipo_Acceso_Paso_Aprobacion" ("ID_Tipo_Acceso_Paso_Aprobacion")
);
-- Historial completo: las decisiones anteriores quedan con Vigente = 'N'
-- (al reabrir por un cambio de datos o por una corrección del solicitante).
-- Sin índice único: HANA no admite índices parciales (ver equivalencias);
-- "una sola decisión vigente por persona y paso" lo garantiza el procedimiento.
CREATE INDEX "IX_CAF_Solicitud_Decision_Persona" ON "CAF_Solicitud_Decision" ("ID_Solicitud_Persona","Vigente");
CREATE INDEX "IX_CAF_Solicitud_Decision_Paso"    ON "CAF_Solicitud_Decision" ("ID_Tipo_Acceso_Paso_Aprobacion","Vigente");

