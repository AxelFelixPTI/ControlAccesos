-- -----------------------------------------------------------------------------
-- 2.1 Tipo_Acceso_Paso_Aprobacion  (los pasos de cada flujo)
--     Orden    : 1, 2, 3... Los pasos con el MISMO orden corren en paralelo;
--                el siguiente se habilita cuando terminan los anteriores.
--     Alcance  : PERSONA  -> se decide persona por persona (documentos, SCTR)
--                SOLICITUD-> una decisión vale para todas (aprobar el servicio)
--     Tipo_Aprobador: hoy solo ROL. Para "el jefe del solicitante" (P-16) se
--                amplía este CHECK y se agrega el dato en Personal.
--     Condicion: SIEMPRE hoy. Una condición nueva exige ampliar el CHECK y
--                enseñar al procedimiento a evaluarla.
--     Obligatorio: 'N' deja un paso informativo que no bloquea la autorización.
-- -----------------------------------------------------------------------------
CREATE TABLE "Tipo_Acceso_Paso_Aprobacion" (
    "ID_Tipo_Acceso_Paso_Aprobacion" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Tipo_Acceso" BIGINT       NOT NULL,
    "Orden"                   BIGINT       NOT NULL,
    "Codigo"                  VARCHAR(50)  NOT NULL,
    "Descripcion"             VARCHAR(500) NOT NULL,
    "Alcance"                 VARCHAR(20)  DEFAULT 'PERSONA' NOT NULL,
    "Tipo_Aprobador"          VARCHAR(20)  DEFAULT 'ROL' NOT NULL,
    "ID_Catalogo_Licencia"    BIGINT,                      -- ref. CAF_GOVERNANCE.Catalogo_Licencia (sin FK física, D-06)
    "Condicion"               VARCHAR(30)  DEFAULT 'SIEMPRE' NOT NULL,
    "Obligatorio"             CHAR(1)      DEFAULT 'Y' NOT NULL,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Tipo_Acceso_Paso_Aprobacion" PRIMARY KEY ("ID_Tipo_Acceso_Paso_Aprobacion"),
    CONSTRAINT "UQ_Tipo_Acceso_Paso_Aprobacion" UNIQUE ("ID_Catalogo_Tipo_Acceso","Codigo"),
    CONSTRAINT "CK_Tipo_Acceso_Paso_Alcance" CHECK ("Alcance" IN ('PERSONA','SOLICITUD')),
    CONSTRAINT "CK_Tipo_Acceso_Paso_Aprobador" CHECK ("Tipo_Aprobador" IN ('ROL')),
    CONSTRAINT "CK_Tipo_Acceso_Paso_Condicion" CHECK ("Condicion" IN ('SIEMPRE')),
    CONSTRAINT "CK_Tipo_Acceso_Paso_Orden" CHECK ("Orden" >= 1),
    CONSTRAINT "CK_Tipo_Acceso_Paso_Rol" CHECK ("Tipo_Aprobador" <> 'ROL' OR "ID_Catalogo_Licencia" IS NOT NULL),
    CONSTRAINT "CK_Tipo_Acceso_Paso_Flags" CHECK ("Obligatorio" IN ('Y','N') AND "Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_Tipo_Acceso_Paso_Tipo" FOREIGN KEY ("ID_Catalogo_Tipo_Acceso") REFERENCES "Catalogo_Tipo_Acceso" ("ID_Catalogo_Tipo_Acceso")
);
CREATE INDEX "IX_Tipo_Acceso_Paso_Tipo" ON "Tipo_Acceso_Paso_Aprobacion" ("ID_Catalogo_Tipo_Acceso","Eliminado","Orden");

-- -----------------------------------------------------------------------------
-- 2.2 CAF_Solicitud_Persona: aprobación por persona
--     Aprobacion: PENDIENTE -> APROBADA | OBSERVADA | RECHAZADA; RETIRADA la
--     pone el solicitante al quitar a alguien (no se borra la fila).
--     Origen: de dónde salió la persona, para la pantalla y el historial.
