-- Datos propios de cada TRANSPORTISTA de una solicitud de proveedor (una fila por persona marcada
-- como transportista). Todos son opcionales: el solicitante puede dejarlos en blanco si esa
-- información viaja en los documentos adjuntos. DNI y nombres no están aquí: son los de la persona
-- (CAF_Solicitud_Persona / CAF_Persona_Externa) y siempre son obligatorios.
-- El transportista PRINCIPAL (CAF_Solicitud_Persona.Es_Principal = 'Y') además se copia a las columnas
-- de CAF_Solicitud (placa, RUC, dirección, marca, licencia) para no tocar el calendario ni Vigilancia.
-- Se agrega Eliminado para el retiro lógico, igual que el resto de tablas.
-- HANA: sin cambios de tipo; la unicidad (una fila por persona) se valida en el SP (sin índices parciales).
-- Aditivo: solo crea una tabla. Va en una transacción y se ejecuta UNA vez.
-- =============================================================================

BEGIN;

DO $$
BEGIN
    IF to_regclass('"TRIANONSATELITAL_CAF_PRODD"."CAF_Solicitud_Persona"') IS NULL THEN
        RAISE EXCEPTION 'Faltan los scripts 01 a 22: no existe CAF_Solicitud_Persona.';
    END IF;
    IF to_regclass('"TRIANONSATELITAL_CAF_PRODD"."CAF_Solicitud_Transportista"') IS NOT NULL THEN
        RAISE EXCEPTION 'El script 23 ya se ejecutó. No se repite.';
    END IF;
END $$;

SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

CREATE TABLE "CAF_Solicitud_Transportista" (
    "ID_Solicitud_Transportista" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"          BIGINT        NOT NULL,
    "ID_Solicitud_Persona"  BIGINT        NOT NULL,
    "Ruc"                   VARCHAR(11),
    "Nombre"                VARCHAR(200),
    "Direccion"             VARCHAR(300),
    "Placa"                 VARCHAR(15),
    "Marca"                 VARCHAR(50),
    "Licencia"              VARCHAR(20),
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Transportista" PRIMARY KEY ("ID_Solicitud_Transportista"),
    CONSTRAINT "CK_CAF_Solicitud_Transportista_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Transportista_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud"),
    CONSTRAINT "FK_CAF_Solicitud_Transportista_Persona" FOREIGN KEY ("ID_Solicitud_Persona") REFERENCES "CAF_Solicitud_Persona" ("ID_Solicitud_Persona")
);
CREATE INDEX "IX_CAF_Solicitud_Transportista_Solicitud" ON "CAF_Solicitud_Transportista" ("ID_Solicitud","Eliminado");
CREATE INDEX "IX_CAF_Solicitud_Transportista_Persona" ON "CAF_Solicitud_Transportista" ("ID_Solicitud_Persona");

-- Las solicitudes de proveedor que ya existen tienen un solo transportista (el principal): se migra con sus datos.
INSERT INTO "CAF_Solicitud_Transportista" ("ID_Solicitud","ID_Solicitud_Persona","Ruc","Direccion","Placa","Marca","Licencia","UsuarioID_Create")
SELECT P."ID_Solicitud", P."ID_Solicitud_Persona", S."Proveedor_RUC", S."Proveedor_Direccion", S."Placa_Vehiculo", S."Vehiculo_Marca", S."Licencia_Conducir", 0
  FROM "CAF_Solicitud_Persona" P
  JOIN "CAF_Solicitud" S ON S."ID_Solicitud" = P."ID_Solicitud"
 WHERE P."Es_Principal" = 'Y' AND P."Eliminado" = 'N';

COMMIT;
