-- Subtipos de persona dentro de un tipo de ingreso (ej. Proveedor: Transportista y Ayudante de descarga) y checklist por subtipo.
--   1. Tabla Tipo_Acceso_Subtipo (los define el desarrollo junto con el flujo: la regla que dice a qué subtipo pertenece cada persona
--      vive en ERP_CAF_FN_SUBTIPO_PERSONA). El administrador los ve y los usa al asignar el checklist.
--   2. Columna ID_Tipo_Acceso_Subtipo (opcional) en Tipo_Acceso_Item_Checklist: NULL = el ítem aplica a todas las personas del tipo.
--   3. Migración: los ítems del Proveedor que usaban las condiciones SOLO_PRINCIPAL / SOLO_AYUDANTE pasan a «Siempre» + subtipo.
-- Se puede ejecutar más de una vez. Schema: TRIANONSATELITAL_CAF_PRODD.
-- HANA: no admite ADD COLUMN IF NOT EXISTS ni CREATE TABLE IF NOT EXISTS: en HANA se ejecuta una sola vez sin esos IF.
-- =============================================================================
SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

CREATE TABLE IF NOT EXISTS "Tipo_Acceso_Subtipo" (
    "ID_Tipo_Acceso_Subtipo" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Tipo_Acceso" BIGINT       NOT NULL,
    "Codigo"                 VARCHAR(50)  NOT NULL,
    "Descripcion"            VARCHAR(200) NOT NULL,
    "Orden"                  BIGINT       DEFAULT 0 NOT NULL,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Tipo_Acceso_Subtipo" PRIMARY KEY ("ID_Tipo_Acceso_Subtipo"),
    CONSTRAINT "UQ_Tipo_Acceso_Subtipo" UNIQUE ("ID_Catalogo_Tipo_Acceso","Codigo"),
    CONSTRAINT "CK_Tipo_Acceso_Subtipo_Flags" CHECK ("Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_Tipo_Acceso_Subtipo_Tipo" FOREIGN KEY ("ID_Catalogo_Tipo_Acceso") REFERENCES "Catalogo_Tipo_Acceso" ("ID_Catalogo_Tipo_Acceso")
);

ALTER TABLE "Tipo_Acceso_Item_Checklist" ADD COLUMN IF NOT EXISTS "ID_Tipo_Acceso_Subtipo" BIGINT;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Tipo_Acceso_Item_Checklist_Subtipo') THEN
        ALTER TABLE "Tipo_Acceso_Item_Checklist" ADD CONSTRAINT "FK_Tipo_Acceso_Item_Checklist_Subtipo"
            FOREIGN KEY ("ID_Tipo_Acceso_Subtipo") REFERENCES "Tipo_Acceso_Subtipo" ("ID_Tipo_Acceso_Subtipo");
    END IF;
END $$;

INSERT INTO "Tipo_Acceso_Subtipo" ("ID_Catalogo_Tipo_Acceso","Codigo","Descripcion","Orden","UsuarioID_Create")
SELECT t."ID_Catalogo_Tipo_Acceso", x.cod, x.descr, x.ord, 0
  FROM "Catalogo_Tipo_Acceso" t
 CROSS JOIN (VALUES ('TRANSPORTISTA','Transportista',1), ('AYUDANTE_DESCARGA','Ayudante de descarga',2)) AS x(cod, descr, ord)
 WHERE t."Codigo" = 'PROVEEDOR'
   AND NOT EXISTS (SELECT 1 FROM "Tipo_Acceso_Subtipo" s WHERE s."ID_Catalogo_Tipo_Acceso" = t."ID_Catalogo_Tipo_Acceso" AND s."Codigo" = x.cod);

-- Migración: solo ítems cuyas asignaciones vigentes son todas del Proveedor (si no, no se toca: cambiaría su efecto en otro tipo)
UPDATE "Tipo_Acceso_Item_Checklist" P
   SET "ID_Tipo_Acceso_Subtipo" = (SELECT s."ID_Tipo_Acceso_Subtipo" FROM "Tipo_Acceso_Subtipo" s
                                    WHERE s."ID_Catalogo_Tipo_Acceso" = P."ID_Catalogo_Tipo_Acceso"
                                      AND s."Codigo" = CASE I."Condicion" WHEN 'SOLO_PRINCIPAL' THEN 'TRANSPORTISTA' ELSE 'AYUDANTE_DESCARGA' END),
       "UsuarioID_Update" = 0, "UpdateDate" = CURRENT_TIMESTAMP
  FROM "Catalogo_Item_Checklist" I, "Catalogo_Tipo_Acceso" T
 WHERE I."ID_Catalogo_Item_Checklist" = P."ID_Catalogo_Item_Checklist"
   AND T."ID_Catalogo_Tipo_Acceso" = P."ID_Catalogo_Tipo_Acceso" AND T."Codigo" = 'PROVEEDOR'
   AND I."Condicion" IN ('SOLO_PRINCIPAL','SOLO_AYUDANTE') AND P."Eliminado" = 'N' AND P."ID_Tipo_Acceso_Subtipo" IS NULL
   AND NOT EXISTS (SELECT 1 FROM "Tipo_Acceso_Item_Checklist" O
                    WHERE O."ID_Catalogo_Item_Checklist" = I."ID_Catalogo_Item_Checklist" AND O."Eliminado" = 'N' AND O."ID_Catalogo_Tipo_Acceso" <> P."ID_Catalogo_Tipo_Acceso");

UPDATE "Catalogo_Item_Checklist" I
   SET "Condicion" = 'SIEMPRE', "UsuarioID_Update" = 0, "UpdateDate" = CURRENT_TIMESTAMP
 WHERE I."Condicion" IN ('SOLO_PRINCIPAL','SOLO_AYUDANTE')
   AND EXISTS (SELECT 1 FROM "Tipo_Acceso_Item_Checklist" P WHERE P."ID_Catalogo_Item_Checklist" = I."ID_Catalogo_Item_Checklist" AND P."Eliminado" = 'N')
   AND NOT EXISTS (SELECT 1 FROM "Tipo_Acceso_Item_Checklist" P WHERE P."ID_Catalogo_Item_Checklist" = I."ID_Catalogo_Item_Checklist" AND P."Eliminado" = 'N' AND P."ID_Tipo_Acceso_Subtipo" IS NULL);
