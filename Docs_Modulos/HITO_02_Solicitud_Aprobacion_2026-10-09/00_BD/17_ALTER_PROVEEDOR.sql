-- 4. Operación del proveedor -----------------------------------------------------------------------
CREATE TABLE "CAF_Solicitud_Operacion" (
    "ID_Solicitud_Operacion" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"           BIGINT       NOT NULL,
    "Estado_Operativo"       VARCHAR(20)  NOT NULL,
    "Activa"                 CHAR(1)      DEFAULT 'Y' NOT NULL,       -- 'N' = la solicitud dejó de estar aprobada o fue cancelada
    "Fecha_Llegada"          TIMESTAMP,
    "ID_Usuario_Llegada"     BIGINT,
    "Fecha_Ingreso"          TIMESTAMP,
    "Fecha_Inicio_Atencion"  TIMESTAMP,
    "ID_Usuario_Atencion"    BIGINT,
    "ID_Personal_Almacen"    BIGINT,                                  -- opcional: quién atiende en Almacén
    "Fecha_Recepcion"        TIMESTAMP,
    "Resultado_Recepcion"    VARCHAR(20),
    "Observacion_Recepcion"  VARCHAR(1000),
    "ID_Usuario_Recepcion"   BIGINT,
    "Fecha_Salida"           TIMESTAMP,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Operacion" PRIMARY KEY ("ID_Solicitud_Operacion"),
    CONSTRAINT "UQ_CAF_Solicitud_Operacion_Solicitud" UNIQUE ("ID_Solicitud"),
    CONSTRAINT "CK_CAF_Solicitud_Operacion_Estado" CHECK ("Estado_Operativo" IN ('PROGRAMADO','EN_ESPERA','INGRESO','EN_ATENCION','RECEPCIONADO','SALIO','NO_SE_PRESENTO')),
    CONSTRAINT "CK_CAF_Solicitud_Operacion_Resultado" CHECK ("Resultado_Recepcion" IS NULL OR "Resultado_Recepcion" IN ('CONFORME','CON_OBSERVACION')),
    CONSTRAINT "CK_CAF_Solicitud_Operacion_Flags" CHECK ("Activa" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Operacion_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);
CREATE INDEX "IX_CAF_Solicitud_Operacion_Estado" ON "CAF_Solicitud_Operacion" ("Activa","Estado_Operativo");

CREATE TABLE "CAF_Solicitud_Operacion_Evento" (
    "ID_Operacion_Evento" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"        BIGINT       NOT NULL,
    "Estado_Anterior"     VARCHAR(20),
    "Estado_Nuevo"        VARCHAR(20)  NOT NULL,
    "ID_Usuario"          BIGINT       NOT NULL,                      -- 0 = sistema
    "Fecha_Evento"        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "Resultado"           VARCHAR(20),
    "Observacion"         VARCHAR(1000),
    CONSTRAINT "PK_CAF_Solicitud_Operacion_Evento" PRIMARY KEY ("ID_Operacion_Evento"),
    CONSTRAINT "FK_CAF_Solicitud_Operacion_Evento_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);
CREATE INDEX "IX_CAF_Solicitud_Operacion_Evento_Solicitud" ON "CAF_Solicitud_Operacion_Evento" ("ID_Solicitud","Fecha_Evento");

