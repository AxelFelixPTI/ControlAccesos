-- Qué hace (aditivo; no cambia ni borra datos de solicitudes ya creadas):
--   1. Catalogo_Sede.Aplica_Proveedor: en qué sedes se permite el proveedor (VES = 'Y').
--   2. CAF_Solicitud: empresa Trianon destinataria, RUC, dirección, marca del vehículo y licencia
--      de conducir del transportista. ID_Personal_Responsable pasa a ser opcional (el proveedor no
--      tiene «responsable de atención»). Se relaja CK_CAF_Solicitud_Cochera: para el proveedor la
--      placa es obligatoria y esa regla vive en la función de validación, no en un CHECK.
--   3. CAF_Solicitud_Persona.Es_Principal: marca al transportista principal (sin él no procede nadie).
--   4. CAF_Solicitud_Operacion (1:1 con la solicitud) y CAF_Solicitud_Operacion_Evento (solo se agrega):
--      estado OPERATIVO del proveedor, separado del estado de aprobación.
--   5. Permisos y licencias nuevos (nadie los tiene hasta que el administrador los asigne).
--   6. Zona fija «Esclusa vehicular» (VES) y motivo fijo «Entrega de proveedor».
--   7. Checklist: condición SOLO_PRINCIPAL, ítem ING_PLACA, y los ítems que aplican al proveedor
--      (identificación, SCTR, EPP y placa). El proveedor no tiene checklist de salida.
--   8. Tipo PROVEEDOR pasa a «Disponible» con un paso de aprobación (licencia nueva de Coordinador de
--      Proveedores). Como nadie la tiene todavía, el tipo se ve pero no se puede usar hasta asignarla.
-- HANA: ALTER TABLE ... ADD ("col" tipo ...); ALTER COLUMN ... NULL; las restricciones CHECK se
--       recrean con DROP CONSTRAINT / ADD CONSTRAINT.
-- Va en una transacción y se ejecuta UNA vez.
-- =============================================================================

