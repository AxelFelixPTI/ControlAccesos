-- Una solicitud = una empresa, un día, una o varias personas (RN-02).
-- La aprobación vive en CAF_Solicitud; el estado de ingreso, en
-- CAF_Solicitud_Persona (una fila por visitante).
-- Referencias a CAF_GOVERNANCE (sede, usuario, personal): sin FK física (D-06).
