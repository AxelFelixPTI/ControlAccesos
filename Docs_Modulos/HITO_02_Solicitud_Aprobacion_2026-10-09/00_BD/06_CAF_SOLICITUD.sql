SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

-- -----------------------------------------------------------------------------
-- 1. CAF_Solicitud
--    Codigo: 'SOL-' + ID con 5 dígitos; lo asigna el SP de creación (D-15).
--    Exige_SCTR / Exige_EPP: copia de lo que exigían las zonas al enviar, para
--    que un cambio posterior en el catálogo no altere solicitudes pasadas (D-18).
--    Version: sube cada vez que la solicitud se reenvía a aprobación.
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Solicitud" (
    "ID_Solicitud"              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"                    VARCHAR(20),
    "ID_Catalogo_Sede"          BIGINT        NOT NULL,   -- ref. CAF_GOVERNANCE.Catalogo_Sede
    "ID_Catalogo_Tipo_Acceso"   BIGINT        NOT NULL,
    "ID_Usuario_Solicitante"    BIGINT        NOT NULL,   -- ref. CAF_GOVERNANCE.Usuario
    "ID_Personal_Responsable"   BIGINT        NOT NULL,   -- ref. CAF_GOVERNANCE.Personal (responsable de atención)
    "Fecha_Hora_Prevista"       TIMESTAMP     NOT NULL,
    "Empresa_Visitante"         VARCHAR(500)  NOT NULL,
    "ID_Catalogo_Motivo_Visita" BIGINT        NOT NULL,
    "Motivo_Detalle"            VARCHAR(500),             -- obligatorio si el motivo es "Otro"
    "Observaciones"             VARCHAR(2000),
    "Exige_SCTR"                CHAR(1)   DEFAULT 'N' NOT NULL,
    "Exige_EPP"                 CHAR(1)   DEFAULT 'N' NOT NULL,
    "Estado"                    VARCHAR(20)   NOT NULL,
    "Version"                   BIGINT    DEFAULT 1 NOT NULL,
    "Fecha_Envio"               TIMESTAMP,
    "ID_Usuario_Decision"       BIGINT,                   -- último Coordinador que aprobó u observó
    "Fecha_Decision"            TIMESTAMP,
    "Observacion_Coordinador"   VARCHAR(2000),            -- última observación (el historial está en CAF_Evento)
    "Motivo_Cancelacion"        VARCHAR(500),
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud" PRIMARY KEY ("ID_Solicitud"),
    CONSTRAINT "UQ_CAF_Solicitud_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "CK_CAF_Solicitud_Estado" CHECK ("Estado" IN ('PENDIENTE','OBSERVADA','APROBADA','CANCELADA')),
    CONSTRAINT "CK_CAF_Solicitud_Version" CHECK ("Version" >= 1),
    CONSTRAINT "CK_CAF_Solicitud_Flags" CHECK ("Exige_SCTR" IN ('Y','N') AND "Exige_EPP" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Tipo_Acceso" FOREIGN KEY ("ID_Catalogo_Tipo_Acceso")   REFERENCES "Catalogo_Tipo_Acceso" ("ID_Catalogo_Tipo_Acceso"),
    CONSTRAINT "FK_CAF_Solicitud_Motivo"      FOREIGN KEY ("ID_Catalogo_Motivo_Visita") REFERENCES "Catalogo_Motivo_Visita" ("ID_Catalogo_Motivo_Visita")
);
-- Bandeja del Coordinador y listado de Vigilancia: por sede, estado y fecha.
CREATE INDEX "IX_CAF_Solicitud_Sede_Estado_Fecha" ON "CAF_Solicitud" ("ID_Catalogo_Sede","Estado","Fecha_Hora_Prevista");
-- "Mis solicitudes" del Solicitante.
CREATE INDEX "IX_CAF_Solicitud_Solicitante" ON "CAF_Solicitud" ("ID_Usuario_Solicitante","Eliminado","Fecha_Hora_Prevista");

-- -----------------------------------------------------------------------------
-- 2. CAF_Solicitud_Version  (foto de lo que se aprobó; RN-08)
--    Contenido_JSON guarda la solicitud completa (datos, zonas, personas) tal
--    como se aprobó. Excepción justificada a "sin textos largos": es una tabla
--    transaccional de solo escritura que no se agrupa ni se filtra por ese campo.
--    HANA: NCLOB.
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Solicitud_Version" (
    "ID_Solicitud_Version" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"         BIGINT    NOT NULL,
    "Version"              BIGINT    NOT NULL,
    "Contenido_JSON"       TEXT      NOT NULL,
    "ID_Usuario_Aprobador" BIGINT    NOT NULL,
    "Fecha_Aprobacion"     TIMESTAMP NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Version" PRIMARY KEY ("ID_Solicitud_Version"),
    CONSTRAINT "UQ_CAF_Solicitud_Version" UNIQUE ("ID_Solicitud","Version"),
    CONSTRAINT "CK_CAF_Solicitud_Version_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Version_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);

-- -----------------------------------------------------------------------------
-- 3. CAF_Solicitud_Zona  (PIVOT: zonas que puede recorrer la visita)
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Solicitud_Zona" (
    "ID_Solicitud_Zona"       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"            BIGINT NOT NULL,
    "ID_Catalogo_Zona_Acceso" BIGINT NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Zona" PRIMARY KEY ("ID_Solicitud_Zona"),
    CONSTRAINT "UQ_CAF_Solicitud_Zona" UNIQUE ("ID_Solicitud","ID_Catalogo_Zona_Acceso"),
    CONSTRAINT "CK_CAF_Solicitud_Zona_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Zona_Solicitud" FOREIGN KEY ("ID_Solicitud")            REFERENCES "CAF_Solicitud" ("ID_Solicitud"),
    CONSTRAINT "FK_CAF_Solicitud_Zona_Zona"      FOREIGN KEY ("ID_Catalogo_Zona_Acceso") REFERENCES "Catalogo_Zona_Acceso" ("ID_Catalogo_Zona_Acceso")
);

-- -----------------------------------------------------------------------------
-- 4. CAF_Solicitud_Persona  (cada visitante dentro de una solicitud)
--    Estado, Fecha_Hora_Ingreso y Fecha_Hora_Salida son el resumen rápido para
--    las pantallas; el detalle y la evidencia están en CAF_Registro_Acceso (D-18).
--    Trae_Equipos / Trae_Herramientas se fijan al ingresar y deciden los ítems
--    de la salida (RN-15).
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Solicitud_Persona" (
    "ID_Solicitud_Persona" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"         BIGINT      NOT NULL,
    "ID_Persona_Externa"   BIGINT      NOT NULL,
    "Estado"               VARCHAR(20) DEFAULT 'ESPERADA' NOT NULL,
    "Acceso_Restringido"   CHAR(1)     DEFAULT 'N' NOT NULL,
    "Trae_Equipos"         CHAR(1)     DEFAULT 'N' NOT NULL,
    "Trae_Herramientas"    CHAR(1)     DEFAULT 'N' NOT NULL,
    "Fecha_Hora_Ingreso"   TIMESTAMP,
    "Fecha_Hora_Salida"    TIMESTAMP,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Persona" PRIMARY KEY ("ID_Solicitud_Persona"),
    CONSTRAINT "UQ_CAF_Solicitud_Persona" UNIQUE ("ID_Solicitud","ID_Persona_Externa"),     -- RN-21: sin documentos repetidos
    CONSTRAINT "CK_CAF_Solicitud_Persona_Estado" CHECK ("Estado" IN ('ESPERADA','DENTRO','SALIO','DENEGADA','NO_SE_PRESENTO')),
    CONSTRAINT "CK_CAF_Solicitud_Persona_Flags" CHECK ("Acceso_Restringido" IN ('Y','N') AND "Trae_Equipos" IN ('Y','N') AND "Trae_Herramientas" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Persona_Solicitud" FOREIGN KEY ("ID_Solicitud")       REFERENCES "CAF_Solicitud" ("ID_Solicitud"),
    CONSTRAINT "FK_CAF_Solicitud_Persona_Persona"   FOREIGN KEY ("ID_Persona_Externa") REFERENCES "CAF_Persona_Externa" ("ID_Persona_Externa")
);
CREATE INDEX "IX_CAF_Solicitud_Persona_Persona" ON "CAF_Solicitud_Persona" ("ID_Persona_Externa","Estado");
CREATE INDEX "IX_CAF_Solicitud_Persona_Estado"  ON "CAF_Solicitud_Persona" ("Estado","Eliminado");

-- -----------------------------------------------------------------------------
-- 5. CAF_Solicitud_Copia_Correo  (destinatarios en copia elegidos al enviar; RF-14)
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Solicitud_Copia_Correo" (
    "ID_Solicitud_Copia_Correo" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"              BIGINT       NOT NULL,
    "Correo"                    VARCHAR(200) NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Copia_Correo" PRIMARY KEY ("ID_Solicitud_Copia_Correo"),
    CONSTRAINT "UQ_CAF_Solicitud_Copia_Correo" UNIQUE ("ID_Solicitud","Correo"),
    CONSTRAINT "CK_CAF_Solicitud_Copia_Correo_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Solicitud_Copia_Correo_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);

-- -----------------------------------------------------------------------------
-- 6. CAF_Evento  (bitácora; RF-38, RNF-04)
--    INMUTABLE: solo se inserta. Por eso NO lleva Eliminado, UsuarioID_Update ni
--    UpdateDate (excepción deliberada a la auditoría estándar, D-16).
--    ID_Usuario = 0 cuando la acción la hace el sistema (p. ej. "No se presentó").
--    ID_Solicitud se repite aquí para armar el historial de una solicitud sin cruces.
--    La pareja Entidad + Accion válida NO se controla en la tabla (D-23): la valida
--    el único procedimiento que escribe aquí, ERP_CAF_EVENTO_REGISTRAR, contra esta matriz:
--      SOLICITUD         CREAR, EDITAR, ENVIAR, APROBAR, OBSERVAR, CANCELAR
--      SOLICITUD_PERSONA NO_SE_PRESENTO
--      REGISTRO_ACCESO   INGRESO, SALIDA
--      DESVIACION        REGISTRAR, CONFORMIDAD
--      INCIDENCIA        REGISTRAR, CONFIRMAR, DESESTIMAR
--      PERSONA_EXTERNA   CREAR, CORREGIR_DATOS
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Evento" (
    "ID_Evento"        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Entidad"          VARCHAR(50)   NOT NULL,
    "ID_Entidad"       BIGINT        NOT NULL,
    "ID_Solicitud"     BIGINT,
    "Accion"           VARCHAR(50)   NOT NULL,
    "Detalle"          VARCHAR(2000),
    "ID_Usuario"       BIGINT        NOT NULL,
    "Fecha_Evento"     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UsuarioID_Create" BIGINT        NOT NULL,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT "PK_CAF_Evento" PRIMARY KEY ("ID_Evento"),
    CONSTRAINT "CK_CAF_Evento_Entidad" CHECK ("Entidad" IN ('SOLICITUD','SOLICITUD_PERSONA','REGISTRO_ACCESO','DESVIACION','INCIDENCIA','PERSONA_EXTERNA'))
);
CREATE INDEX "IX_CAF_Evento_Solicitud" ON "CAF_Evento" ("ID_Solicitud","Fecha_Evento");
CREATE INDEX "IX_CAF_Evento_Entidad"   ON "CAF_Evento" ("Entidad","ID_Entidad");
