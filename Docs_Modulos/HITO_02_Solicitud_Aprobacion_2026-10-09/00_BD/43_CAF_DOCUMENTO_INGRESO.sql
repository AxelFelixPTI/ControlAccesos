-- Script  : 43_CAF_DOCUMENTO_INGRESO.sql   (2026-11-22, D-265)
-- Propósito: documentos de ingreso que sube Vigilancia DESPUÉS de registrar entradas y salidas (actas, guías, registros de
--            equipos y herramientas, normalmente PDFs escaneados). Un documento es del DÍA y puede corresponder a varias
--            personas, incluso de solicitudes distintas.
--              CAF_Documento_Ingreso          el archivo (contenido en la base, como los adjuntos de la solicitud)
--              CAF_Documento_Ingreso_Persona  vínculo documento ↔ persona de una solicitud (de ahí salen la solicitud y la empresa)
--            Parámetros: DOCUMENTO_INGRESO_OBLIGATORIO (Y/N, por defecto N: solo marca «pendiente», no bloquea nada) y
--            DOCUMENTO_INGRESO_MAX_MB (1 a 30, por defecto 10). Idempotente.
-- Nota HANA: BYTEA → BLOB; GENERATED BY DEFAULT AS IDENTITY; el índice único parcial se reescribe con una columna calculada (T-60).
-- =============================================================================
SET search_path TO "TRIANONSATELITAL_CAF_PRODD", "CAF_GOVERNANCE";

CREATE TABLE IF NOT EXISTS "CAF_Documento_Ingreso" (
    "ID_Documento_Ingreso" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Sede"     BIGINT        NOT NULL,
    "Fecha_Registro"       DATE          NOT NULL,                      -- el día de ingreso al que corresponde el documento
    "Tipo"                 VARCHAR(20)   NOT NULL,                      -- EQUIPOS | HERRAMIENTAS | GUIA | OTRO
    "Nombre_Archivo"       VARCHAR(200)  NOT NULL,
    "Extension"            VARCHAR(10)   NOT NULL,
    "Tipo_Contenido"       VARCHAR(100)  NOT NULL,
    "Tamano_Bytes"         BIGINT        NOT NULL,
    "Hash_SHA256"          CHAR(64)      NOT NULL,
    "Contenido"            BYTEA         NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Documento_Ingreso" PRIMARY KEY ("ID_Documento_Ingreso"),
    CONSTRAINT "CK_CAF_Documento_Ingreso_Tipo" CHECK ("Tipo" IN ('EQUIPOS','HERRAMIENTAS','GUIA','OTRO')),
    CONSTRAINT "CK_CAF_Documento_Ingreso_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "CK_CAF_Documento_Ingreso_Tamano" CHECK ("Tamano_Bytes" > 0)
);
CREATE INDEX IF NOT EXISTS "IX_CAF_Documento_Ingreso_Dia" ON "CAF_Documento_Ingreso" ("ID_Catalogo_Sede","Fecha_Registro","Eliminado");

CREATE TABLE IF NOT EXISTS "CAF_Documento_Ingreso_Persona" (
    "ID_Documento_Ingreso_Persona" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Documento_Ingreso"         BIGINT NOT NULL,
    "ID_Solicitud_Persona"         BIGINT NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Documento_Ingreso_Persona" PRIMARY KEY ("ID_Documento_Ingreso_Persona"),
    CONSTRAINT "CK_CAF_Documento_Ingreso_Persona_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Doc_Ingreso_Persona_Doc" FOREIGN KEY ("ID_Documento_Ingreso") REFERENCES "CAF_Documento_Ingreso" ("ID_Documento_Ingreso"),
    CONSTRAINT "FK_CAF_Doc_Ingreso_Persona_Per" FOREIGN KEY ("ID_Solicitud_Persona") REFERENCES "CAF_Solicitud_Persona" ("ID_Solicitud_Persona")
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_CAF_Documento_Ingreso_Persona" ON "CAF_Documento_Ingreso_Persona" ("ID_Documento_Ingreso","ID_Solicitud_Persona") WHERE "Eliminado" = 'N';
CREATE INDEX IF NOT EXISTS "IX_CAF_Documento_Ingreso_Persona_Per" ON "CAF_Documento_Ingreso_Persona" ("ID_Solicitud_Persona") WHERE "Eliminado" = 'N';

INSERT INTO "CAF_Parametro" ("Clave","Valor","Descripcion","UsuarioID_Create")
SELECT 'DOCUMENTO_INGRESO_OBLIGATORIO', 'N', 'Si cada persona que trae equipos o herramientas debe tener un documento de ingreso (Y/N). Por defecto N. Solo marca pendiente; no bloquea ingresos ni salidas.', 0
 WHERE NOT EXISTS (SELECT 1 FROM "CAF_Parametro" WHERE "Clave" = 'DOCUMENTO_INGRESO_OBLIGATORIO');
INSERT INTO "CAF_Parametro" ("Clave","Valor","Descripcion","UsuarioID_Create")
SELECT 'DOCUMENTO_INGRESO_MAX_MB', '10', 'Tamaño máximo en MB de un documento de ingreso (de 1 a 30). Por defecto 10.', 0
 WHERE NOT EXISTS (SELECT 1 FROM "CAF_Parametro" WHERE "Clave" = 'DOCUMENTO_INGRESO_MAX_MB');
