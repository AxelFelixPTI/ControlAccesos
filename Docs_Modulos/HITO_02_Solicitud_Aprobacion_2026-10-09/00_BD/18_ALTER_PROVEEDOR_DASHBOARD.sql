-- Hito    : 2 - Solicitud y aprobacion | Fase 0 - DDL y datos (Entrega 2 de Proveedor de abastecimiento)
-- Version : V1.0 2026-11-03
-- Estado  : CANDIDATO - probado en PostgreSQL 16 sobre la base con 01 a 17
-- Requiere: scripts 01 a 17 ejecutados.
-- =============================================================================
-- Que hace (aditivo; no cambia ni borra datos):
--   1. CAF_Solicitud_Operacion: responsable de atencion PROGRAMADO (informativo, opcional), con quien y cuando
--      lo asigno. El responsable EFECTIVO sigue siendo ID_Usuario_Atencion / ID_Personal_Almacen (quien
--      presiono Atender); no se sobrescribe el programado.
--   2. CAF_Solicitud_Operacion_Evento: columna ID_Personal_Programado para dejar en el historial cada
--      asignacion o cambio del programado.
--   3. CAF_Exclusa: UN registro por sede = recurso unico compartido. Mientras ID_Solicitud_Actual no es NULL,
--      la esclusa esta ocupada. Ocuparla es un UPDATE condicionado (atomico), asi dos usuarios que pulsan
--      Atender a la vez no pueden ocuparla ambos. (HANA no tiene indices unicos parciales; por eso se usa
--      una fila-candado en lugar de un indice sobre EN_ATENCION.)
--   4. Permiso PER_CAF_PROVEEDOR_DASHBOARD (solo lectura del calendario) y licencia LIC_CAF_PROVEEDOR_DASHBOARD,
--      aparte de las demas. La licencia de Almacen tambien incluye el permiso para que vea el calendario.
--      Nadie tiene la licencia nueva hasta que el administrador la asigne.
-- HANA: ALTER TABLE ... ADD ("col" tipo); la fila de CAF_Exclusa se siembra con INSERT ... SELECT.
-- Va en una transaccion y se ejecuta UNA vez.
-- =============================================================================

BEGIN;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                    WHERE table_schema = 'TRIANONSATELITAL_CAF_PRODD' AND table_name = 'CAF_Solicitud' AND column_name = 'Proveedor_RUC') THEN
        RAISE EXCEPTION 'Falta el script 17.';
    END IF;
    IF to_regclass('"TRIANONSATELITAL_CAF_PRODD"."CAF_Exclusa"') IS NOT NULL THEN
        RAISE EXCEPTION 'El script 18 ya se ejecuto. No se repite.';
    END IF;
END $$;

SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

-- 1. Responsable programado -----------------------------------------------------------------------
ALTER TABLE "CAF_Solicitud_Operacion" ADD COLUMN "ID_Personal_Programado"    BIGINT;     -- ref. CAF_GOVERNANCE.Personal (de Almacen)
ALTER TABLE "CAF_Solicitud_Operacion" ADD COLUMN "ID_Usuario_Programacion"   BIGINT;     -- quien lo asigno
ALTER TABLE "CAF_Solicitud_Operacion" ADD COLUMN "Fecha_Programacion"        TIMESTAMP;

-- 2. Historial -------------------------------------------------------------------------------------
ALTER TABLE "CAF_Solicitud_Operacion_Evento" ADD COLUMN "ID_Personal_Programado" BIGINT;

-- 3. Esclusa (recurso unico por sede) ------------------------------------------------------------
CREATE TABLE "CAF_Exclusa" (
    "ID_Exclusa"         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Sede"   BIGINT    NOT NULL,                 -- ref. CAF_GOVERNANCE.Catalogo_Sede
    "ID_Solicitud_Actual" BIGINT,                            -- NULL = libre
    "Fecha_Ocupada"      TIMESTAMP,
    "ID_Usuario_Ocupa"   BIGINT,
    "Eliminado"          CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create"   BIGINT    NOT NULL,
    "UsuarioID_Update"   BIGINT,
    "CreateDate"         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"         TIMESTAMP,
    CONSTRAINT "PK_CAF_Exclusa" PRIMARY KEY ("ID_Exclusa"),
    CONSTRAINT "UQ_CAF_Exclusa_Sede" UNIQUE ("ID_Catalogo_Sede"),
    CONSTRAINT "CK_CAF_Exclusa_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Exclusa_Solicitud" FOREIGN KEY ("ID_Solicitud_Actual") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);

INSERT INTO "CAF_Exclusa" ("ID_Catalogo_Sede","UsuarioID_Create")
SELECT s."ID_Catalogo_Sede", 0
  FROM "CAF_GOVERNANCE"."Catalogo_Sede" s
 WHERE s."Aplica_Proveedor" = 'Y' AND s."Eliminado" = 'N';

-- 4. Permiso y licencia del dashboard -----------------------------------------------------------
SET search_path TO "CAF_GOVERNANCE";
INSERT INTO "Catalogo_Permiso" ("Codigo","Descripcion","Modulo","Orden","UsuarioID_Create")
VALUES ('PER_CAF_PROVEEDOR_DASHBOARD','Ver el calendario de entregas de proveedores (solo lectura)','ACCESOS',18,0);

INSERT INTO "Catalogo_Licencia" ("Codigo","Descripcion","Modulo","Orden","UsuarioID_Create")
VALUES ('LIC_CAF_PROVEEDOR_DASHBOARD','Calendario de entregas de proveedores (solo lectura)','ACCESOS',24,0);

INSERT INTO "Licencia_Permiso" ("ID_Catalogo_Licencia","ID_Catalogo_Permiso","UsuarioID_Create")
SELECT l."ID_Catalogo_Licencia", p."ID_Catalogo_Permiso", 0
  FROM (VALUES
    ('LIC_CAF_PROVEEDOR_DASHBOARD','PER_CAF_PROVEEDOR_DASHBOARD'),
    ('LIC_CAF_ALMACEN',            'PER_CAF_PROVEEDOR_DASHBOARD')
  ) AS v(lic, per)
  JOIN "Catalogo_Licencia" l ON l."Codigo" = v.lic
  JOIN "Catalogo_Permiso"  p ON p."Codigo" = v.per;

COMMIT;
