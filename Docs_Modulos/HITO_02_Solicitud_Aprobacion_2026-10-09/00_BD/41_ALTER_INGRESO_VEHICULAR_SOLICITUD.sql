-- Propósito: coordinación entre almaceneros al «Confirmar disponibilidad» CON ingreso vehicular.
--   1. Tabla CAF_Solicitud_Ingreso_Vehicular: la solicitud que hace un almacenero (entrega ID_Solicitud) al almacenero que tiene en curso
--      otra entrega (ID_Solicitud_Otra) con vehículos aún por ingresar. Estados: PENDIENTE, CONFIRMADA, RECHAZADA, RETIRADA.
--   2. Permiso PER_CAF_PROVEEDOR_COORD_ALMACEN y licencia LIC_CAF_COORD_ALMACEN («Coordinador de Almacén»): un almacenero con esta
--      licencia (ADEMÁS de LIC_CAF_ALMACEN) puede decidir la solicitud en lugar del almacenero que no responde. No es el rol Coordinador
--      que aprueba solicitudes.
-- Se puede ejecutar más de una vez. Schema: TRIANONSATELITAL_CAF_PRODD (tabla) y CAF_GOVERNANCE (permiso y licencia).
-- HANA (T-56): sin CREATE TABLE IF NOT EXISTS (consultar SYS.TABLES); ON DELETE CASCADE existe en HANA; sin índices parciales.
-- =============================================================================
SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

CREATE TABLE IF NOT EXISTS "CAF_Solicitud_Ingreso_Vehicular" (
    "ID_Solicitud_Ingreso"   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"           BIGINT       NOT NULL,                      -- la entrega que quiere ingresar vehículos (la que solicita)
    "ID_Solicitud_Otra"      BIGINT       NOT NULL,                      -- la entrega en curso, con vehículos por ingresar, a la que se le pide conformidad
    "ID_Usuario_Solicita"    BIGINT       NOT NULL,
    "ID_Usuario_Responsable" BIGINT,                                     -- almacenero de la entrega en curso al pedir (NULL si la reserva estaba cedida)
    "Estado"                 VARCHAR(12)  DEFAULT 'PENDIENTE' NOT NULL,
    "Motivo_Rechazo"         VARCHAR(200),                               -- opcional
    "Fecha_Decision"         TIMESTAMP,
    "ID_Usuario_Decide"      BIGINT,
    "Decidida_Por_Coord"     CHAR(1)      DEFAULT 'N' NOT NULL,          -- 'Y' = la decidió el Coordinador de Almacén por el almacenero
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Ingreso_Vehicular" PRIMARY KEY ("ID_Solicitud_Ingreso"),
    CONSTRAINT "CK_CAF_Solicitud_Ingreso_Vehicular_Estado" CHECK ("Estado" IN ('PENDIENTE','CONFIRMADA','RECHAZADA','RETIRADA')),
    CONSTRAINT "CK_CAF_Solicitud_Ingreso_Vehicular_Flags" CHECK ("Eliminado" IN ('Y','N') AND "Decidida_Por_Coord" IN ('Y','N')),
    CONSTRAINT "CK_CAF_Solicitud_Ingreso_Vehicular_Distintas" CHECK ("ID_Solicitud" <> "ID_Solicitud_Otra"),
    CONSTRAINT "FK_CAF_Solicitud_Ingreso_Vehicular_Sol" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud") ON DELETE CASCADE,
    CONSTRAINT "FK_CAF_Solicitud_Ingreso_Vehicular_Otra" FOREIGN KEY ("ID_Solicitud_Otra") REFERENCES "CAF_Solicitud" ("ID_Solicitud") ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS "IX_CAF_Solicitud_Ingreso_Vehicular_Sol" ON "CAF_Solicitud_Ingreso_Vehicular" ("ID_Solicitud","Estado");
CREATE INDEX IF NOT EXISTS "IX_CAF_Solicitud_Ingreso_Vehicular_Otra" ON "CAF_Solicitud_Ingreso_Vehicular" ("ID_Solicitud_Otra","Estado");

SET search_path TO "CAF_GOVERNANCE";

INSERT INTO "Catalogo_Permiso" ("Codigo","Descripcion","Modulo","Orden","UsuarioID_Create")
SELECT 'PER_CAF_PROVEEDOR_COORD_ALMACEN','Coordinador de Almacén: decidir solicitudes de ingreso vehicular por otro almacenero','ACCESOS',20,0
 WHERE NOT EXISTS (SELECT 1 FROM "Catalogo_Permiso" WHERE "Codigo"='PER_CAF_PROVEEDOR_COORD_ALMACEN');

INSERT INTO "Catalogo_Licencia" ("Codigo","Descripcion","Modulo","Orden","UsuarioID_Create")
SELECT 'LIC_CAF_COORD_ALMACEN','Coordinador de Almacén: decide solicitudes de ingreso vehicular entre almaceneros (se suma a la licencia de Almacén)','ACCESOS',27,0
 WHERE NOT EXISTS (SELECT 1 FROM "Catalogo_Licencia" WHERE "Codigo"='LIC_CAF_COORD_ALMACEN');

INSERT INTO "Licencia_Permiso" ("ID_Catalogo_Licencia","ID_Catalogo_Permiso","UsuarioID_Create")
SELECT l."ID_Catalogo_Licencia", p."ID_Catalogo_Permiso", 0
  FROM "Catalogo_Licencia" l
  JOIN "Catalogo_Permiso"  p ON p."Codigo" = 'PER_CAF_PROVEEDOR_COORD_ALMACEN'
 WHERE l."Codigo" = 'LIC_CAF_COORD_ALMACEN'
   AND NOT EXISTS (SELECT 1 FROM "Licencia_Permiso" lp
                    WHERE lp."ID_Catalogo_Licencia" = l."ID_Catalogo_Licencia" AND lp."ID_Catalogo_Permiso" = p."ID_Catalogo_Permiso");
