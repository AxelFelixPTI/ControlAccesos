-- Documentos adjuntos de una solicitud (PDF, Word, Excel). Se guardan en la propia base (un solo
-- respaldo, sin carpetas del servidor) y pertenecen a la SOLICITUD, no a una persona: un SCTR trae
-- varios nombres en un solo archivo. Máximo 2 por solicitud y 5 MB cada uno (lo valida el SP).
--   Hash_SHA256   evita adjuntar dos veces el mismo archivo y deja evidencia de lo que se envió.
-- Borrado lógico (Eliminado = 'Y'): el contenido se conserva como evidencia.
-- HANA: "Contenido" pasa a BLOB; BYTEA/encode/sha256 de los SP pasan a BLOB/BINTOHEX(HASH_SHA256()).
-- Aditivo: solo crea una tabla. Va en una transacción y se ejecuta UNA vez.
-- =============================================================================

BEGIN;

DO $$
BEGIN
    IF to_regclass('"TRIANONSATELITAL_CAF_PRODD"."CAF_Solicitud"') IS NULL THEN
        RAISE EXCEPTION 'Faltan los scripts 06 a 14: no existe CAF_Solicitud.';
    END IF;
    IF to_regclass('"TRIANONSATELITAL_CAF_PRODD"."CAF_Solicitud_Adjunto"') IS NOT NULL THEN
        RAISE EXCEPTION 'El script 15 ya se ejecutó. No se repite.';
    END IF;
END $$;

SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

CREATE TABLE "CAF_Solicitud_Adjunto" (
    "ID_Solicitud_Adjunto" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud"         BIGINT        NOT NULL,
    "Nombre_Archivo"       VARCHAR(200)  NOT NULL,
    "Extension"            VARCHAR(10)   NOT NULL,
    "Tipo_Contenido"       VARCHAR(100)  NOT NULL,
    "Tamano_Bytes"         BIGINT        NOT NULL,
    "Hash_SHA256"          CHAR(64)      NOT NULL,
    "Contenido"            BYTEA         NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Solicitud_Adjunto" PRIMARY KEY ("ID_Solicitud_Adjunto"),
    CONSTRAINT "CK_CAF_Solicitud_Adjunto_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "CK_CAF_Solicitud_Adjunto_Tamano" CHECK ("Tamano_Bytes" > 0 AND "Tamano_Bytes" <= 5242880),
    CONSTRAINT "FK_CAF_Solicitud_Adjunto_Solicitud" FOREIGN KEY ("ID_Solicitud") REFERENCES "CAF_Solicitud" ("ID_Solicitud")
);
CREATE INDEX "IX_CAF_Solicitud_Adjunto_Solicitud" ON "CAF_Solicitud_Adjunto" ("ID_Solicitud","Eliminado");

COMMIT;
