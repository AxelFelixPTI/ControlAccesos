-- -----------------------------------------------------------------------------
-- 4. Catalogo_Tratamiento_Desviacion  (RN-11, RN-22; G-PSCA-003 §5.3.c)
--    El efecto depende de la etapa: Resultado_Ingreso / Resultado_Salida.
--    NULL = no aplica en esa etapa. Para "Otro" ambos son NULL y el registro
--    de la desviación indica el efecto elegido por Vigilancia.
-- -----------------------------------------------------------------------------
CREATE TABLE "Catalogo_Tratamiento_Desviacion" (
    "ID_Catalogo_Tratamiento_Desviacion" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"            VARCHAR(50)  NOT NULL,
    "Descripcion"       VARCHAR(500) NOT NULL,
    "Aplica_Ingreso"    CHAR(1)   DEFAULT 'N' NOT NULL,
    "Aplica_Salida"     CHAR(1)   DEFAULT 'N' NOT NULL,
    "Resultado_Ingreso" VARCHAR(30),
    "Resultado_Salida"  VARCHAR(30),
    "Es_Otro"           CHAR(1)   DEFAULT 'N' NOT NULL,
    "Orden"            BIGINT    DEFAULT 0   NOT NULL,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Catalogo_Tratamiento_Desviacion" PRIMARY KEY ("ID_Catalogo_Tratamiento_Desviacion"),
    CONSTRAINT "UQ_Catalogo_Tratamiento_Desviacion_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "CK_Catalogo_Tratamiento_Desviacion_Res_Ing" CHECK ("Resultado_Ingreso" IS NULL OR "Resultado_Ingreso" IN ('INGRESA','INGRESA_RESTRINGIDO','NO_INGRESA')),
    CONSTRAINT "CK_Catalogo_Tratamiento_Desviacion_Res_Sal" CHECK ("Resultado_Salida" IS NULL OR "Resultado_Salida" IN ('SALE','SALE_RETIENE_ELEMENTO')),
    CONSTRAINT "CK_Catalogo_Tratamiento_Desviacion_Flags" CHECK ("Aplica_Ingreso" IN ('Y','N') AND "Aplica_Salida" IN ('Y','N') AND "Es_Otro" IN ('Y','N') AND "Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N'))
);
CREATE INDEX "IX_Catalogo_Tratamiento_Desviacion_Activa" ON "Catalogo_Tratamiento_Desviacion" ("Eliminado","Activo","Orden");

