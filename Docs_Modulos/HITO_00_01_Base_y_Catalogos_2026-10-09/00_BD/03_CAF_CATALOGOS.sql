-- -----------------------------------------------------------------------------
-- 1. Catalogo_Tipo_Acceso
-- -----------------------------------------------------------------------------
CREATE TABLE "Catalogo_Tipo_Acceso" (
    "ID_Catalogo_Tipo_Acceso" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"               VARCHAR(50)  NOT NULL,
    "Descripcion"          VARCHAR(500) NOT NULL,
    "Requiere_Aprobacion"  CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Disponible"           CHAR(1)   DEFAULT 'N' NOT NULL,
    "Orden"            BIGINT    DEFAULT 0   NOT NULL,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Catalogo_Tipo_Acceso" PRIMARY KEY ("ID_Catalogo_Tipo_Acceso"),
    CONSTRAINT "UQ_Catalogo_Tipo_Acceso_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "CK_Catalogo_Tipo_Acceso_Flags" CHECK ("Requiere_Aprobacion" IN ('Y','N') AND "Disponible" IN ('Y','N') AND "Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N'))
);
CREATE INDEX "IX_Catalogo_Tipo_Acceso_Activa" ON "Catalogo_Tipo_Acceso" ("Eliminado","Activo","Orden");

-- -----------------------------------------------------------------------------
-- 2. Catalogo_Zona_Acceso  (por sede; RN-09)
-- -----------------------------------------------------------------------------
CREATE TABLE "Catalogo_Zona_Acceso" (
    "ID_Catalogo_Zona_Acceso" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Sede" BIGINT       NOT NULL,   -- ref. CAF_GOVERNANCE.Catalogo_Sede (sin FK física)
    "Codigo"           VARCHAR(50)  NOT NULL,
    "Descripcion"      VARCHAR(500) NOT NULL,
    "Tipo_Zona"        VARCHAR(20)  NOT NULL,
    "Exige_SCTR"       CHAR(1)   DEFAULT 'N' NOT NULL,
    "Exige_EPP"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "Orden"            BIGINT    DEFAULT 0   NOT NULL,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Catalogo_Zona_Acceso" PRIMARY KEY ("ID_Catalogo_Zona_Acceso"),
    CONSTRAINT "UQ_Catalogo_Zona_Acceso_Sede_Codigo" UNIQUE ("ID_Catalogo_Sede","Codigo"),
    CONSTRAINT "CK_Catalogo_Zona_Acceso_Tipo" CHECK ("Tipo_Zona" IN ('ADMINISTRATIVA','OPERATIVA')),
    CONSTRAINT "CK_Catalogo_Zona_Acceso_Flags" CHECK ("Exige_SCTR" IN ('Y','N') AND "Exige_EPP" IN ('Y','N') AND "Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N'))
);
CREATE INDEX "IX_Catalogo_Zona_Acceso_Activa" ON "Catalogo_Zona_Acceso" ("ID_Catalogo_Sede","Eliminado","Activo","Orden");

