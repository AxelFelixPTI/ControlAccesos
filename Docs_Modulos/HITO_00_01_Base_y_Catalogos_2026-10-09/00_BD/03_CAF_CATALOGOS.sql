-- -----------------------------------------------------------------------------
-- 6. Catalogo_Item_Checklist  (RN-10, RN-12, RN-15)
--    Condicion decide cuándo se muestra el ítem; Es_Critico marca los que, sin
--    cumplir, obligan a denegar (identidad, G-PSCA-003 §4.3).
-- -----------------------------------------------------------------------------
CREATE TABLE "Catalogo_Item_Checklist" (
    "ID_Catalogo_Item_Checklist" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"           VARCHAR(50)  NOT NULL,
    "Descripcion"      VARCHAR(500) NOT NULL,
    "Ayuda"            VARCHAR(500),
    "Etapa"            VARCHAR(10)  NOT NULL,
    "Condicion"        VARCHAR(30)  NOT NULL,
    "Es_Critico"       CHAR(1)   DEFAULT 'N' NOT NULL,
    "Orden"            BIGINT    DEFAULT 0   NOT NULL,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Catalogo_Item_Checklist" PRIMARY KEY ("ID_Catalogo_Item_Checklist"),
    CONSTRAINT "UQ_Catalogo_Item_Checklist_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "CK_Catalogo_Item_Checklist_Etapa" CHECK ("Etapa" IN ('INGRESO','SALIDA')),
    CONSTRAINT "CK_Catalogo_Item_Checklist_Condicion" CHECK ("Condicion" IN ('SIEMPRE','ZONA_EXIGE_SCTR','ZONA_EXIGE_EPP','TRAE_EQUIPOS','TRAE_HERRAMIENTAS')),
    CONSTRAINT "CK_Catalogo_Item_Checklist_Flags" CHECK ("Es_Critico" IN ('Y','N') AND "Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N'))
);
CREATE INDEX "IX_Catalogo_Item_Checklist_Activa" ON "Catalogo_Item_Checklist" ("Etapa","Eliminado","Activo","Orden");

-- -----------------------------------------------------------------------------
-- 7. Tipo_Acceso_Item_Checklist  (PIVOT N:N: qué ítems aplican a cada tipo de acceso)
-- -----------------------------------------------------------------------------
CREATE TABLE "Tipo_Acceso_Item_Checklist" (
    "ID_Tipo_Acceso_Item_Checklist" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Tipo_Acceso"       BIGINT NOT NULL,
    "ID_Catalogo_Item_Checklist"    BIGINT NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Tipo_Acceso_Item_Checklist" PRIMARY KEY ("ID_Tipo_Acceso_Item_Checklist"),
    CONSTRAINT "UQ_Tipo_Acceso_Item_Checklist" UNIQUE ("ID_Catalogo_Tipo_Acceso","ID_Catalogo_Item_Checklist"),
    CONSTRAINT "CK_Tipo_Acceso_Item_Checklist_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_Tipo_Acceso_Item_Checklist_Tipo" FOREIGN KEY ("ID_Catalogo_Tipo_Acceso")    REFERENCES "Catalogo_Tipo_Acceso" ("ID_Catalogo_Tipo_Acceso"),
    CONSTRAINT "FK_Tipo_Acceso_Item_Checklist_Item" FOREIGN KEY ("ID_Catalogo_Item_Checklist") REFERENCES "Catalogo_Item_Checklist" ("ID_Catalogo_Item_Checklist")
);
CREATE INDEX "IX_Tipo_Acceso_Item_Checklist_Tipo" ON "Tipo_Acceso_Item_Checklist" ("ID_Catalogo_Tipo_Acceso","Eliminado");
