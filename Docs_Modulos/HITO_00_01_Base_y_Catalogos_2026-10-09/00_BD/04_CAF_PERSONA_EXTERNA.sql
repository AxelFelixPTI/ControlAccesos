-- Registro reutilizable de personas externas (RN-20, RN-21, HU-03).
-- Se identifica por tipo + número de documento. No se borra: si hace falta
-- corregirla se actualiza; el UNIQUE no filtra por "Eliminado" (HANA no admite
-- índices parciales), por eso nunca se marca 'Y' una persona que ya visitó.
-- El nombre va en tres columnas, como "Personal", para búsquedas y una futura
-- consulta a RENIEC. Impacto en el mockup S-03: el campo único "Apellidos y
-- nombres" pasa a ser tres campos (o uno que la app separe).
-- =============================================================================

SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

CREATE TABLE "CAF_Persona_Externa" (
    "ID_Persona_Externa"         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Tipo_Documento" BIGINT       NOT NULL,   -- ref. CAF_GOVERNANCE (sin FK física)
    "Numero_Documento"           VARCHAR(20)  NOT NULL,
    "Apellido_Paterno"           VARCHAR(100) NOT NULL,
    "Apellido_Materno"           VARCHAR(100),
    "Nombres"                    VARCHAR(200) NOT NULL,
    "Fecha_Ultima_Visita"        TIMESTAMP,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Persona_Externa" PRIMARY KEY ("ID_Persona_Externa"),
    CONSTRAINT "UQ_CAF_Persona_Externa_Documento" UNIQUE ("ID_Catalogo_Tipo_Documento","Numero_Documento"),
    CONSTRAINT "CK_CAF_Persona_Externa_Flags" CHECK ("Eliminado" IN ('Y','N'))
);
-- Búsqueda por nombre (consultas del Coordinador y reportes).
CREATE INDEX "IX_CAF_Persona_Externa_Nombre" ON "CAF_Persona_Externa" ("Apellido_Paterno","Nombres");
