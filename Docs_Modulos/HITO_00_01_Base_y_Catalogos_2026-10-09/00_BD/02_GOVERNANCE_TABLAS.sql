--   * nombres entre comillas dobles, PascalCase con guion bajo;
--   * PK "ID_<Tabla>" BIGINT IDENTITY; catálogos "Catalogo_<X>" sin LOB;
--   * auditoría al final: Orden y Activo (catálogos), Eliminado, UsuarioID_Create,
--     UsuarioID_Update, CreateDate, UpdateDate;
--   * borrado lógico con "Eliminado" CHAR(1) 'N'/'Y';
--   * nombres de restricciones PK_ / UQ_ / CK_ / FK_ / IX_.
-- Tipos: VARCHAR aquí = NVARCHAR en HANA (ver Docs_BD/EQUIVALENCIAS_POSTGRESQL_HANA.md).
-- Las FK solo se declaran DENTRO del mismo schema.
