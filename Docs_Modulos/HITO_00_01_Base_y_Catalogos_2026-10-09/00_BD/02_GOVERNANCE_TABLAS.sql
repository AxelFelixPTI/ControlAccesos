-- -----------------------------------------------------------------------------
-- 6. Personal  (catálogo de trabajadores: de aquí sale el responsable de atención)
--    Estar en Personal NO da acceso al sistema; eso lo da Usuario + Usuario_Licencia.
-- -----------------------------------------------------------------------------
CREATE TABLE "Personal" (
    "ID_Personal"                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Tipo_Documento" BIGINT       NOT NULL,
    "Numero_Documento"           VARCHAR(20)  NOT NULL,
    "Apellido_Paterno"           VARCHAR(100) NOT NULL,
    "Apellido_Materno"           VARCHAR(100),
    "Nombres"                    VARCHAR(200) NOT NULL,
    "ID_Catalogo_Area"           BIGINT       NOT NULL,
    "ID_Catalogo_Cargo"          BIGINT,
    "ID_Catalogo_Empresa_Grupo"  BIGINT       NOT NULL,
    "ID_Catalogo_Sede"           BIGINT       NOT NULL,
    "Correo"                     VARCHAR(200),
    "Anexo"                      VARCHAR(20),
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Personal" PRIMARY KEY ("ID_Personal"),
    CONSTRAINT "UQ_Personal_Documento" UNIQUE ("ID_Catalogo_Tipo_Documento","Numero_Documento"),
    CONSTRAINT "CK_Personal_Flags" CHECK ("Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_Personal_Tipo_Documento" FOREIGN KEY ("ID_Catalogo_Tipo_Documento") REFERENCES "Catalogo_Tipo_Documento" ("ID_Catalogo_Tipo_Documento"),
    CONSTRAINT "FK_Personal_Area"           FOREIGN KEY ("ID_Catalogo_Area")           REFERENCES "Catalogo_Area" ("ID_Catalogo_Area"),
    CONSTRAINT "FK_Personal_Cargo"          FOREIGN KEY ("ID_Catalogo_Cargo")          REFERENCES "Catalogo_Cargo" ("ID_Catalogo_Cargo"),
    CONSTRAINT "FK_Personal_Empresa_Grupo"  FOREIGN KEY ("ID_Catalogo_Empresa_Grupo")  REFERENCES "Catalogo_Empresa_Grupo" ("ID_Catalogo_Empresa_Grupo"),
    CONSTRAINT "FK_Personal_Sede"           FOREIGN KEY ("ID_Catalogo_Sede")           REFERENCES "Catalogo_Sede" ("ID_Catalogo_Sede")
);
-- Búsqueda del responsable de atención por apellido o nombre (HU-02).
CREATE INDEX "IX_Personal_Busqueda" ON "Personal" ("Eliminado","Activo","Apellido_Paterno","Nombres");
CREATE INDEX "IX_Personal_Sede_Area" ON "Personal" ("ID_Catalogo_Sede","ID_Catalogo_Area");

-- -----------------------------------------------------------------------------
-- 7. Usuario  (cuenta personal para entrar al sistema; RN-23: nunca compartida)
--    Puede o no estar ligado a Personal: los vigilantes son contratistas.
--    La contraseña se guarda como hash generado por la aplicación, nunca en claro.
-- -----------------------------------------------------------------------------
CREATE TABLE "Usuario" (
    "ID_Usuario"                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Correo"                     VARCHAR(200) NOT NULL,
    "ID_Catalogo_Tipo_Documento" BIGINT       NOT NULL,
    "Numero_Documento"           VARCHAR(20)  NOT NULL,
    "Apellido_Paterno"           VARCHAR(100) NOT NULL,
    "Apellido_Materno"           VARCHAR(100),
    "Nombres"                    VARCHAR(200) NOT NULL,
    "ID_Personal"                BIGINT,
    "Empresa_Externa"            VARCHAR(500),
    "Password_Hash"              VARCHAR(500),
    "Password_Requiere_Cambio"   CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Token_Restablecer_Hash"     VARCHAR(500),
    "Token_Restablecer_Expira"   TIMESTAMP,
    "Intentos_Fallidos"          BIGINT    DEFAULT 0 NOT NULL,
    "Bloqueado_Hasta"            TIMESTAMP,
    "Ultimo_Acceso"              TIMESTAMP,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Usuario" PRIMARY KEY ("ID_Usuario"),
    CONSTRAINT "UQ_Usuario_Correo" UNIQUE ("Correo"),
    CONSTRAINT "UQ_Usuario_Documento" UNIQUE ("ID_Catalogo_Tipo_Documento","Numero_Documento"),
    CONSTRAINT "CK_Usuario_Flags" CHECK ("Password_Requiere_Cambio" IN ('Y','N') AND "Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "CK_Usuario_Intentos" CHECK ("Intentos_Fallidos" >= 0),
    CONSTRAINT "FK_Usuario_Tipo_Documento" FOREIGN KEY ("ID_Catalogo_Tipo_Documento") REFERENCES "Catalogo_Tipo_Documento" ("ID_Catalogo_Tipo_Documento"),
    CONSTRAINT "FK_Usuario_Personal"       FOREIGN KEY ("ID_Personal")                REFERENCES "Personal" ("ID_Personal")
);
CREATE INDEX "IX_Usuario_Activo" ON "Usuario" ("Eliminado","Activo","Apellido_Paterno");

