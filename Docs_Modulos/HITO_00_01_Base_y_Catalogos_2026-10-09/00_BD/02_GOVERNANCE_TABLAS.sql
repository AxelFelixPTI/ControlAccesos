SET search_path TO "CAF_GOVERNANCE";

-- -----------------------------------------------------------------------------
-- 1. Catalogo_Sede
-- -----------------------------------------------------------------------------
CREATE TABLE "Catalogo_Sede" (
    "ID_Catalogo_Sede" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"           VARCHAR(50)  NOT NULL,
    "Descripcion"      VARCHAR(500) NOT NULL,
    "Direccion"        VARCHAR(500),
    "Orden"            BIGINT    DEFAULT 0   NOT NULL,
    "Activo"           CHAR(1)   DEFAULT 'Y' NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Catalogo_Sede" PRIMARY KEY ("ID_Catalogo_Sede"),
    CONSTRAINT "UQ_Catalogo_Sede_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "CK_Catalogo_Sede_Flags" CHECK ("Activo" IN ('Y','N') AND "Eliminado" IN ('Y','N'))
);
CREATE INDEX "IX_Catalogo_Sede_Activa" ON "Catalogo_Sede" ("Eliminado","Activo","Orden");

