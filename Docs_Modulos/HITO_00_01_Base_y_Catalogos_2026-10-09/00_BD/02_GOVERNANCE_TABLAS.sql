-- -----------------------------------------------------------------------------
-- 9. Usuario_Licencia  (PIVOT N:N usuario-licencia, por sede)
--    Una fila por usuario, licencia y sede: así Magdalena se habilita con datos.
-- -----------------------------------------------------------------------------
CREATE TABLE "Usuario_Licencia" (
    "ID_Usuario_Licencia"  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Usuario"           BIGINT NOT NULL,
    "ID_Catalogo_Licencia" BIGINT NOT NULL,
    "ID_Catalogo_Sede"     BIGINT NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_Usuario_Licencia" PRIMARY KEY ("ID_Usuario_Licencia"),
    CONSTRAINT "UQ_Usuario_Licencia" UNIQUE ("ID_Usuario","ID_Catalogo_Licencia","ID_Catalogo_Sede"),
    CONSTRAINT "CK_Usuario_Licencia_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_Usuario_Licencia_Usuario"  FOREIGN KEY ("ID_Usuario")           REFERENCES "Usuario" ("ID_Usuario"),
    CONSTRAINT "FK_Usuario_Licencia_Licencia" FOREIGN KEY ("ID_Catalogo_Licencia") REFERENCES "Catalogo_Licencia" ("ID_Catalogo_Licencia"),
    CONSTRAINT "FK_Usuario_Licencia_Sede"     FOREIGN KEY ("ID_Catalogo_Sede")     REFERENCES "Catalogo_Sede" ("ID_Catalogo_Sede")
);
CREATE INDEX "IX_Usuario_Licencia_Usuario" ON "Usuario_Licencia" ("ID_Usuario","Eliminado");
