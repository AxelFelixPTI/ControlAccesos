SET search_path TO "TRIANONSATELITAL_CAF_PRODD";

-- -----------------------------------------------------------------------------
-- 1. CAF_Registro_Acceso  (un ingreso o una salida de una persona)
--    Fecha_Hora: hora del hecho. La pone el servidor, salvo registro tardío
--    (RN-18), en cuyo caso la indica Vigilancia y Fecha_Hora_Sistema conserva
--    el momento real de la carga.
--    Resultado: efecto final, tras aplicar la decisión si hubo desviación.
--    Un ingreso denegado también es un registro (Resultado = NO_INGRESA).
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Registro_Acceso" (
    "ID_Registro_Acceso"    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Solicitud_Persona"  BIGINT       NOT NULL,
    "ID_Catalogo_Sede"      BIGINT       NOT NULL,   -- ref. CAF_GOVERNANCE.Catalogo_Sede
    "Tipo_Movimiento"       VARCHAR(10)  NOT NULL,
    "Resultado"             VARCHAR(30)  NOT NULL,
    "Fecha_Hora"            TIMESTAMP    NOT NULL,
    "Es_Registro_Tardio"    CHAR(1)   DEFAULT 'N' NOT NULL,
    "Fecha_Hora_Sistema"    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "ID_Usuario_Vigilante"  BIGINT       NOT NULL,   -- ref. CAF_GOVERNANCE.Usuario
    "Observacion"           VARCHAR(1000),
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Registro_Acceso" PRIMARY KEY ("ID_Registro_Acceso"),
    CONSTRAINT "CK_CAF_Registro_Acceso_Tipo" CHECK ("Tipo_Movimiento" IN ('INGRESO','SALIDA')),
    CONSTRAINT "CK_CAF_Registro_Acceso_Resultado" CHECK (
        ("Tipo_Movimiento" = 'INGRESO' AND "Resultado" IN ('INGRESA','INGRESA_RESTRINGIDO','NO_INGRESA'))
     OR ("Tipo_Movimiento" = 'SALIDA'  AND "Resultado" IN ('SALE','SALE_RETIENE_ELEMENTO'))),
    CONSTRAINT "CK_CAF_Registro_Acceso_Flags" CHECK ("Es_Registro_Tardio" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Registro_Acceso_Solicitud_Persona" FOREIGN KEY ("ID_Solicitud_Persona") REFERENCES "CAF_Solicitud_Persona" ("ID_Solicitud_Persona")
);
CREATE INDEX "IX_CAF_Registro_Acceso_Persona" ON "CAF_Registro_Acceso" ("ID_Solicitud_Persona","Tipo_Movimiento");
-- Reporte de ingresos y salidas por sede y rango de fechas (RF-36).
CREATE INDEX "IX_CAF_Registro_Acceso_Reporte" ON "CAF_Registro_Acceso" ("ID_Catalogo_Sede","Fecha_Hora");

-- -----------------------------------------------------------------------------
-- 2. CAF_Registro_Checklist  (una fila por ítem verificado en ese movimiento)
--    Se guardan TODOS los ítems mostrados, cumplan o no: así se sabe qué se
--    verificó, no solo qué falló.
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Registro_Checklist" (
    "ID_Registro_Checklist"      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Registro_Acceso"         BIGINT  NOT NULL,
    "ID_Catalogo_Item_Checklist" BIGINT  NOT NULL,
    "Cumple"                     CHAR(1) NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Registro_Checklist" PRIMARY KEY ("ID_Registro_Checklist"),
    CONSTRAINT "UQ_CAF_Registro_Checklist" UNIQUE ("ID_Registro_Acceso","ID_Catalogo_Item_Checklist"),
    CONSTRAINT "CK_CAF_Registro_Checklist_Flags" CHECK ("Cumple" IN ('Y','N') AND "Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Registro_Checklist_Registro" FOREIGN KEY ("ID_Registro_Acceso")         REFERENCES "CAF_Registro_Acceso" ("ID_Registro_Acceso"),
    CONSTRAINT "FK_CAF_Registro_Checklist_Item"     FOREIGN KEY ("ID_Catalogo_Item_Checklist") REFERENCES "Catalogo_Item_Checklist" ("ID_Catalogo_Item_Checklist")
);

-- -----------------------------------------------------------------------------
-- 3. CAF_Respaldo  (documento físico que ampara lo que trae la persona; RN-14)
--    EQUIPOS              -> formato conjunto G-FSCA-009
--    HERRAMIENTAS_MATERIALES -> guía de remisión o guía manual G-FSCA-010
--    Numero_Documento: solo para guía de remisión (serie-número). El formato
--    físico no tiene correlativo. Los archivos escaneados llegan en la
--    iteración 1.1 en una tabla hija CAF_Respaldo_Documento.
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Respaldo" (
    "ID_Respaldo"          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Catalogo_Sede"     BIGINT       NOT NULL,   -- ref. CAF_GOVERNANCE.Catalogo_Sede
    "Categoria"            VARCHAR(30)  NOT NULL,
    "Tipo_Respaldo"        VARCHAR(30)  NOT NULL,
    "Numero_Documento"     VARCHAR(50),
    "Fecha_Hora"           TIMESTAMP    NOT NULL,
    "ID_Usuario_Vigilante" BIGINT       NOT NULL,   -- ref. CAF_GOVERNANCE.Usuario
    "Observacion"          VARCHAR(1000),
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Respaldo" PRIMARY KEY ("ID_Respaldo"),
    CONSTRAINT "CK_CAF_Respaldo_Tipo" CHECK (
        ("Categoria" = 'EQUIPOS' AND "Tipo_Respaldo" = 'G_FSCA_009')
     OR ("Categoria" = 'HERRAMIENTAS_MATERIALES' AND "Tipo_Respaldo" IN ('GUIA_REMISION','GUIA_MANUAL_G_FSCA_010'))),
    CONSTRAINT "CK_CAF_Respaldo_Flags" CHECK ("Eliminado" IN ('Y','N'))
);
CREATE INDEX "IX_CAF_Respaldo_Sede_Fecha" ON "CAF_Respaldo" ("ID_Catalogo_Sede","Fecha_Hora");

-- -----------------------------------------------------------------------------
-- 4. CAF_Respaldo_Persona  (PIVOT: un respaldo puede cubrir a varias personas)
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Respaldo_Persona" (
    "ID_Respaldo_Persona"  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ID_Respaldo"          BIGINT NOT NULL,
    "ID_Solicitud_Persona" BIGINT NOT NULL,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Respaldo_Persona" PRIMARY KEY ("ID_Respaldo_Persona"),
    CONSTRAINT "UQ_CAF_Respaldo_Persona" UNIQUE ("ID_Respaldo","ID_Solicitud_Persona"),
    CONSTRAINT "CK_CAF_Respaldo_Persona_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Respaldo_Persona_Respaldo" FOREIGN KEY ("ID_Respaldo")          REFERENCES "CAF_Respaldo" ("ID_Respaldo"),
    CONSTRAINT "FK_CAF_Respaldo_Persona_Persona"  FOREIGN KEY ("ID_Solicitud_Persona") REFERENCES "CAF_Solicitud_Persona" ("ID_Solicitud_Persona")
);
CREATE INDEX "IX_CAF_Respaldo_Persona_Persona" ON "CAF_Respaldo_Persona" ("ID_Solicitud_Persona");

-- -----------------------------------------------------------------------------
-- 5. CAF_Desviacion  (RN-11, RN-16; G-PSCA-003 §5.3)
--    Codigo: 'DES-' + ID con 5 dígitos (D-15).
--    Los ítems incumplidos son las filas Cumple = 'N' de su registro.
--    Resultado: efecto de la decisión. Se copia del catálogo; si el tratamiento
--    es "Otro", lo elige Vigilancia (D-11).
--    ID_Incidencia: enlace opcional si algún día se escala a incidencia (backlog).
-- -----------------------------------------------------------------------------
CREATE TABLE "CAF_Desviacion" (
    "ID_Desviacion"                       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo"                              VARCHAR(20),
    "ID_Registro_Acceso"                  BIGINT        NOT NULL,
    "Descripcion"                         VARCHAR(2000) NOT NULL,
    "ID_Usuario_Coordinador_Consultado"   BIGINT        NOT NULL,   -- ref. CAF_GOVERNANCE.Usuario
    "ID_Catalogo_Tratamiento_Desviacion"  BIGINT        NOT NULL,
    "Tratamiento_Detalle"                 VARCHAR(500),             -- obligatorio si el tratamiento es "Otro"
    "Resultado"                           VARCHAR(30)   NOT NULL,
    "Estado"                              VARCHAR(20)   DEFAULT 'POR_REVISAR' NOT NULL,
    "ID_Usuario_Conformidad"              BIGINT,
    "Fecha_Conformidad"                   TIMESTAMP,
    "Comentario_Conformidad"              VARCHAR(1000),
    "ID_Incidencia"                       BIGINT,
    "Eliminado"        CHAR(1)   DEFAULT 'N' NOT NULL,
    "UsuarioID_Create" BIGINT    NOT NULL,
    "UsuarioID_Update" BIGINT,
    "CreateDate"       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "UpdateDate"       TIMESTAMP,
    CONSTRAINT "PK_CAF_Desviacion" PRIMARY KEY ("ID_Desviacion"),
    CONSTRAINT "UQ_CAF_Desviacion_Codigo" UNIQUE ("Codigo"),
    CONSTRAINT "UQ_CAF_Desviacion_Registro" UNIQUE ("ID_Registro_Acceso"),          -- una desviación por movimiento
    CONSTRAINT "CK_CAF_Desviacion_Estado" CHECK ("Estado" IN ('POR_REVISAR','REVISADA')),
    CONSTRAINT "CK_CAF_Desviacion_Resultado" CHECK ("Resultado" IN ('INGRESA','INGRESA_RESTRINGIDO','NO_INGRESA','SALE','SALE_RETIENE_ELEMENTO')),
    CONSTRAINT "CK_CAF_Desviacion_Conformidad" CHECK ("Estado" = 'POR_REVISAR' OR ("ID_Usuario_Conformidad" IS NOT NULL AND "Fecha_Conformidad" IS NOT NULL)),
    CONSTRAINT "CK_CAF_Desviacion_Flags" CHECK ("Eliminado" IN ('Y','N')),
    CONSTRAINT "FK_CAF_Desviacion_Registro"    FOREIGN KEY ("ID_Registro_Acceso")                 REFERENCES "CAF_Registro_Acceso" ("ID_Registro_Acceso"),
    CONSTRAINT "FK_CAF_Desviacion_Tratamiento" FOREIGN KEY ("ID_Catalogo_Tratamiento_Desviacion") REFERENCES "Catalogo_Tratamiento_Desviacion" ("ID_Catalogo_Tratamiento_Desviacion")
);
-- Bandeja "Por revisar" del Coordinador.
CREATE INDEX "IX_CAF_Desviacion_Estado" ON "CAF_Desviacion" ("Estado","Eliminado","CreateDate");
